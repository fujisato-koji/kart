"""Rough numbers for step 1.2 (form): snow sinkage, drive force, cost, and the
snowmobile form with its tub hull on snow and in water.

Reads its inputs from record/values.yaml through tools/tdr.py, and writes its
outputs back as calculated values between the marker comments in that file.

    python calc/form_rough.py          # print
    python calc/form_rough.py --write  # also update record/values.yaml
"""
import importlib.util
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("tdr", ROOT / "tools" / "tdr.py")
tdr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tdr)

BEGIN = "  # begin: generated by calc/form_rough.py"
END = "  # end: generated by calc/form_rough.py"
G = 9.81
RHO_W = 1000  # fresh water, kg/m3


def values():
    rec = tdr.Record(ROOT)
    return {it.d["key"]: it.d["v"] for it in rec.items["value"]}


def compute(v):
    out = []  # (key, value, unit, docs section)

    def put(key, val, unit, sec):
        out.append((key, val, unit, sec))
        v[key] = val

    # Masses and loads
    m = v["kart.mass_rough_kg"] + v["rider.mass_max_kg"]
    put("form.mass_total_kg", round(m), "kg", "mass")
    w = m * G
    rear = w * v["kart.rear_share"]

    # Wheel sinkage in fresh snow (P1): z = h (1 - rho0 / rhof)
    rhof = v["snow.crrel_rhof_a"] + v["snow.crrel_rhof_b"] * v["tyre.pressure_kpa"]
    h = v["snow.depth_max_cm"]
    put("snow.wheel_sinkage_min_cm", round(h * (1 - v["snow.density_initial_max"] / rhof), 1), "cm", "snow")
    put("snow.wheel_sinkage_max_cm", round(h * (1 - v["snow.density_initial_min"] / rhof), 1), "cm", "snow")

    # Rear tracks: contact length of a two-wheel loop, ground pressure
    circ = v["track.pitch_mm"] * v["track.links"]
    contact = (circ - math.pi * v["track.wheel_dia_mm"]) / 2
    area_t = 2 * v["track.width_mm"] * contact / 1e6
    p_t = rear / area_t / 1000
    put("snow.track_pressure_kpa", round(p_t, 1), "kPa", "snow")

    # Front skis
    area_s = 2 * v["ski.width_mm"] * v["ski.contact_length_mm"] / 1e6
    p_s = (w - rear) / area_s / 1000
    put("snow.ski_pressure_kpa", round(p_s, 1), "kPa", "snow")

    # Bekker sinkage z = (p / (kc/b + kphi))^(1/n), three snows from P2, worst case
    def bekker(p, b_mm):
        zs = []
        for s in ("a", "b", "c"):
            k = v[f"snow.bekker_{s}_kc"] / (b_mm / 1000) + v[f"snow.bekker_{s}_kphi"]
            zs.append((p / k) ** (1 / v[f"snow.bekker_{s}_n"]))
        return max(zs) * 100

    put("snow.track_sinkage_max_cm", round(bekker(p_t, v["track.width_mm"]), 1), "cm", "snow")
    put("snow.ski_sinkage_max_cm", round(bekker(p_s, v["ski.width_mm"]), 1), "cm", "snow")

    # Without road wheels the load sits under the sprocket and idler: Bekker's wheel
    # sinkage z = [3W / ((3 - n)(kc + b kphi) sqrt(D))]^(2 / (2n + 1)), worst snow
    def bekker_wheel(load_n, b_mm, d_mm):
        b, d, zs = b_mm / 1000, d_mm / 1000, []
        for s in ("a", "b", "c"):
            n = v[f"snow.bekker_{s}_n"]
            k = (v[f"snow.bekker_{s}_kc"] + b * v[f"snow.bekker_{s}_kphi"]) * 1000
            zs.append((3 * load_n / ((3 - n) * k * math.sqrt(d))) ** (2 / (2 * n + 1)))
        return max(zs) * 100

    put("snow.track_sinkage_wheels_cm", round(bekker_wheel(rear / 4, v["track.width_mm"],
                                                           v["track.wheel_dia_mm"]), 1), "cm", "snow")
    # Deepest fresh snow a wheeled kart clears, light snow: with its floor, and with
    # the lowest part on the rear axle (brake disc or sprocket)
    def depth_limit(clear_mm):
        return round(clear_mm / 10 / (1 - v["snow.density_initial_min"] / rhof), 1)

    put("snow.wheel_depth_limit_cm", depth_limit(v["kart.clearance_rough_mm"]), "cm", "snow")
    put("snow.wheel_depth_limit_axle_cm", depth_limit(v["kart.axle_part_low_rough_mm"]), "cm", "snow")

    # Track width for R-12 with the heaviest rider
    seat = v["kart.clearance_rough_mm"] / 1000 + v["seat.above_floor_rough_m"]
    cg = ((v["kart.mass_rough_kg"] * v["kart.cg_height_rough_m"]
           + v["rider.mass_max_kg"] * (seat + v["rider.cg_above_seat_m"])) / m)
    put("form.cg_height_m", round(cg, 3), "m", "stability")
    put("form.width_overall_m", round(math.ceil(200 * cg * v["kart.tip_ratio_min"]) / 100 + v["tyre.width_mm"] / 1000, 2),
        "m", "transport")
    put("form.track_min_m", math.ceil(200 * cg * v["kart.tip_ratio_min"]) / 100, "m", "stability")
    # The same margin kept across the steepest slope, standing sideways on it
    slope = math.atan(v["site.grade_max_pct"] / 100)
    put("form.track_min_slope_m", math.ceil(200 * cg * math.tan(math.atan(v["kart.tip_ratio_min"]) + slope)) / 100,
        "m", "stability")

    # Drive: gear each power source so that its highest free speed gives the top speed.
    # The engine's force comes from its maximum power at rated speed; a motor's from its
    # rated torque scaled by the controller's current over the motor's rated current.
    r = v["tyre.dia_mm"] / 2000
    wheel_rpm = v["kart.speed_max_kmh"] / 3.6 / (2 * math.pi * r) * 60
    eta = v["drive.efficiency"]
    ratio_e = v["engine.speed_noload_rpm"] / wheel_rpm
    put("drive.engine_ratio", round(ratio_e, 2), None, "drive")
    t_e = v["engine.power_max_kw"] * 1000 / (v["engine.speed_rated_rpm"] * 2 * math.pi / 60)
    put("drive.engine_thrust_n", round(t_e * ratio_e * eta / r), "N", "drive")
    t_c = v["engine.power_cont_kw"] * 1000 / (v["engine.speed_rated_rpm"] * 2 * math.pi / 60)
    put("drive.engine_thrust_cont_n", round(t_c * ratio_e * eta / r), "N", "drive")
    for tag, pre in (("motor", "motor"), ("motor2", "motor2")):
        ratio_m = v[f"{pre}.speed_rated_rpm"] / wheel_rpm
        t_m = v[f"{pre}.torque_rated_nm"] * v[f"{pre}.controller_a"] / v[f"{pre}.current_rated_a"]
        put(f"drive.{tag}_thrust_n", round(t_m * ratio_m * eta / r), "N", "drive")
    # The centrifugal clutch starts to drive at the first speed and slips below the second
    for tag, rpm in (("engage", "clutch.engage_rpm"), ("lock", "clutch.lock_rpm")):
        put(f"drive.clutch_{tag}_kmh", round(v["kart.speed_max_kmh"] * v[rpm] / v["engine.speed_noload_rpm"], 1),
            "km/h", "drive")
    crr = v["ground.crr_max"]
    put("drive.climb_force_n", round(w * (math.sin(slope) + crr * math.cos(slope))), "N", "drive")
    put("drive.grass_power_kw", round(crr * w * v["kart.speed_max_kmh"] / 3.6 / eta / 1000, 2), "kW", "drive")
    # Battery run time at a mean speed on grass with the heaviest rider
    p_avg = v["ground.crr_avg"] * w * v["drive.speed_avg_kmh"] / 3.6 / v["drive.efficiency_electric"]
    put("drive.power_avg_heavy_w", round(p_avg), "W", "drive")
    put("battery.run_time_heavy_min", round(v["battery.energy_wh"] * v["battery.usable_fraction"] / p_avg * 60),
        "min", "drive")
    # One chain stage: axle sprocket with whole teeth, tooth tips (outside diameter)
    teeth = math.ceil(v["sprocket.engine_teeth"] * ratio_e)
    od = v["sprocket.pitch_mm"] * (0.6 + 1 / math.tan(math.pi / teeth))
    put("drive.sprocket_reach_mm", round(v["tyre.dia_mm"] / 2 - od / 2), "mm", "drive")

    # Tub hull (D-023, D-024): an open plastic tub around the seat, its bottom the floor and the
    # sled bottom, with foam inside that floats the swamped kart (R-29). Foam first, from the
    # heavier form and the plating it must carry; then the floating summer kart with its rider,
    # its outboard, and the outboard's battery.
    hl, hb, hd = v["hull.length_mm"] / 1000, v["hull.beam_mm"] / 1000, v["hull.depth_mm"] / 1000
    # the summer kart without the sled pan of 1.3, which this tub stands for
    m_kart = v["dsn.mass_kg"] - v["dsn.pan_mass_kg"]
    bottom, sides = hl * hb, 2 * (hl + hb) * hd
    sheet = (bottom * v["hull.bottom_t_mm"] + sides * v["hull.side_t_mm"]) / 1000 * v["hull.sheet_density_kg_m3"]
    rho_f = v["foam.density_kg_m3"]
    m_dry = max(m_kart, m_kart - v["sm.removed_kg"] + v["sm.track_unit_kg"] + v["ski.pair_kg"])
    foam = v["water.reserve_ratio"] * (m_dry + sheet) / (RHO_W - rho_f)
    put("hull.sheet_kg", round(sheet, 1), "kg", "water")
    put("hull.foam_m3", round(foam, 3), "m3", "water")
    put("hull.foam_share", round(foam / (hl * hb * hd), 2), None, "water")
    m_hull = sheet + foam * rho_f
    put("hull.mass_kg", round(m_hull, 1), "kg", "water")
    m_boat = m_kart + m_hull + v["outboard.mass_kg"] + v["outboard.battery_kg"]
    m_sf = m_boat + v["rider.mass_max_kg"]
    draft = m_sf / RHO_W / (hl * hb)
    put("water.draft_mm", round(draft * 1000), "mm", "water")
    put("water.freeboard_mm", round((hd - draft) * 1000), "mm", "water")
    # Initial stability of a box: GM = KB + BM - KG, with BM = B^2 / (12 T); the centre of mass
    # is the summer kart's with the adult, measured from the tub's bottom
    kg_ = v["dsn.cg_height_adult_m"] - v["hull.bottom_clear_mm"] / 1000
    put("water.gm_m", round(draft / 2 + hb ** 2 / (12 * draft) - kg_, 3), "m", "water")
    # US rule for a small boat of 2 hp or less (P52): the load it may carry is a share of what the
    # tub displaces floating level to its rim, less the boat's own weight
    put("water.load_rating_kg", round(v["water.load_share_manual"] * (hl * hb * hd * RHO_W - m_boat)), "kg", "water")
    put("water.depth_for_rider_mm", round((v["rider.mass_max_kg"] / v["water.load_share_manual"] + m_boat)
                                          / (hl * hb * RHO_W) * 1000), "mm", "water")

    # Japanese rule for the persons a small boat on sheltered water may carry (P55, articles 102
    # and 103): N <= C L B F and N <= L B (F2 - 0.025 L) / 0.33, with F the freeboard without
    # persons (at most B / 5.5 + 0.09), F2 taken equal to F for a level tub, and
    # C = 2.69 - 5.31 (D / B)^2 kept between 0.78 and 2.27
    def persons(l_, b_):
        c = min(2.27, max(0.78, 2.69 - 5.31 * (hd / b_) ** 2))
        f = min(hd - m_boat / RHO_W / (l_ * b_), b_ / 5.5 + 0.09)
        return min(c * l_ * b_ * f, l_ * b_ * (f - 0.025 * l_) / 0.33)

    put("water.persons_rated", math.floor(persons(hl, hb)), None, "water")
    put("water.persons_index", round(persons(hl, hb), 2), None, "water")
    # The beam, at the tub's length and depth, that rates one person (the boat's weight kept)
    b_one = next(b / 100 for b in range(round(hb * 100), 300) if persons(hl, b / 100) >= 1)
    put("water.beam_for_one_mm", round(b_one * 1000), "mm", "water")

    # Snowmobile form (D-023): the summer kart less its wheels and axle, plus a donor's track unit
    # and a pair of skis, in the same tub; the chassis rides sm.lift_mm higher over the track
    m_w = m_kart - v["sm.removed_kg"] + v["sm.track_unit_kg"] + v["ski.pair_kg"] + m_hull
    put("sm.mass_kg", round(m_w, 1), "kg", "snowmobile")
    ww = (m_w + v["rider.mass_max_kg"]) * G
    wb = v["lay.wheelbase_mm"] / 1000
    x_cg = (1 - v["dsn.rear_share_adult"]) * wb  # ahead of the summer rear axle
    x_t = v["sm.track_x_mm"] / 1000
    share = (wb - x_cg) / (wb - x_t)
    put("sm.rear_share", round(share, 2), None, "snowmobile")
    tw, tl = v["sm.track_width_mm"] / 1000, v["sm.track_contact_mm"] / 1000
    p_tr = ww * share / (tw * tl) / 1000
    p_sk = ww * (1 - share) / (2 * v["ski.width_mm"] * v["ski.contact_length_mm"] / 1e6) / 1000
    p_hb = ww / (hl * hb) / 1000
    put("sm.track_pressure_kpa", round(p_tr, 2), "kPa", "snowmobile")
    put("sm.ski_pressure_kpa", round(p_sk, 2), "kPa", "snowmobile")
    put("sm.hull_pressure_kpa", round(p_hb, 2), "kPa", "snowmobile")
    put("sm.track_sinkage_max_cm", round(bekker(p_tr, v["sm.track_width_mm"]), 1), "cm", "snowmobile")
    put("sm.ski_sinkage_max_cm", round(bekker(p_sk, v["ski.width_mm"]), 1), "cm", "snowmobile")
    put("sm.hull_sinkage_max_cm", round(bekker(p_hb, v["hull.beam_mm"]), 1), "cm", "snowmobile")
    # The CVT drives the track's sprocket through the summer chain: the speed at which the
    # centrifugal clutch locks, the top speed, and the power at a slow speed in fresh snow
    circ = math.pi * v["sm.drive_dia_mm"] / 1000 * 60 / 1000  # km per sprocket revolution per hour
    put("sm.clutch_lock_kmh", round(v["su.clutch_lock_rpm"] / v["dsn.ratio"] * circ, 1), "km/h", "snowmobile")
    put("sm.top_speed_kmh", round(v["su.rev_limit_rpm"] / v["dsn.ratio_top"] * circ, 1), "km/h", "snowmobile")
    put("sm.power_snow_kw", round(v["track.crr_snow_fresh"] * ww * v["sm.speed_snow_kmh"] / 3.6
                                  / v["drive.efficiency"] / 1000, 2), "kW", "snowmobile")
    # Tipping on three supports: the edge from a ski's rear end to the track's rear corner,
    # its distance from the centre of mass over the centre of mass's height
    x1, y1 = wb - v["ski.contact_length_mm"] / 2000, v["lay.track_front_mm"] / 2000
    x2, y2 = x_t - tl / 2, tw / 2
    d = abs((y2 - y1) * x_cg + x2 * y1 - y2 * x1) / math.hypot(x2 - x1, y2 - y1)
    raised = (m_w + v["rider.mass_max_kg"] - v["sm.track_unit_kg"] - v["ski.pair_kg"]) / (m_w + v["rider.mass_max_kg"])
    h_w = v["dsn.cg_height_adult_m"] + raised * v["sm.lift_mm"] / 1000
    put("sm.cg_height_m", round(h_w, 3), "m", "snowmobile")
    put("sm.tip_ratio", round(d / h_w, 2), None, "snowmobile")
    # A snowmobile skims open water only above a speed that grows with its weight (S5)
    # Length from the skis' front ends to the rear end of the track's contact
    put("sm.length_min_m", round(wb + v["ski.contact_length_mm"] / 2000 - (x_t - tl / 2), 2), "m", "snowmobile")
    put("sm.skip_speed_kmh", round(v["snow.skip_kmh_per_100kg"] * (m_w + v["rider.mass_max_kg"]) / 100), "km/h", "snowmobile")
    # W4: the sled pan carries most of the weight in fresh snow and the rear tyres, pressed down
    # with a share of it and wearing chains, push. Their sinkage by Bekker's wheel relation (P2),
    # their grip by CRREL's fit for shallow undisturbed snow (P59), against the pan sliding
    # (sled.mu_packed, P60) and the tyres' own resistance (ground.crr_snow_fresh, P1)
    w4w = (v["dsn.mass_kg"] + v["rider.mass_max_kg"]) * G
    td, tw4 = v["yr.tyre_dia_mm"], v["yr.rear_width_mm"]       # the summer tyres, buggy-size (D-032)

    def w4(f, tyres=2, d_mm=None, b_mm=None, bekker_res=False):
        d_mm, b_mm = d_mm or td, b_mm or tw4
        load = f * w4w / tyres
        z = bekker_wheel(load, b_mm, d_mm) / 100
        arc = min(math.sqrt(d_mm / 1000 * z), d_mm / 2000)
        n_ = load / (b_mm / 1000 * arc) / 1000
        grip = tyres * v["snow.crrel_trac_shallow_a"] * n_ ** v["snow.crrel_trac_shallow_b"] * b_mm / 1000 * arc * 1000
        if bekker_res:
            # the work of pressing a rut z deep, b (kc/b + kphi) z^(n+1) / (n+1), in the snow that sinks deepest
            def sink(s_):
                n_s = v[f"snow.bekker_{s_}_n"]
                k_s = (v[f"snow.bekker_{s_}_kc"] + b_mm / 1000 * v[f"snow.bekker_{s_}_kphi"]) * 1000
                return (3 * load / ((3 - n_s) * k_s * math.sqrt(d_mm / 1000))) ** (2 / (2 * n_s + 1))
            s = max("abc", key=sink)
            n = v[f"snow.bekker_{s}_n"]
            rut = b_mm / 1000 * (v[f"snow.bekker_{s}_kc"] / (b_mm / 1000) + v[f"snow.bekker_{s}_kphi"]) * 1000 * z ** (n + 1) / (n + 1)
            res = v["sled.mu_packed"] * (1 - f) * w4w + tyres * rut
        else:
            res = v["sled.mu_packed"] * (1 - f) * w4w + v["ground.crr_snow_fresh"] * f * w4w
        return z, grip, res

    put("w4.share_min", next(f / 100 for f in range(5, 100, 5) if w4(f / 100)[1] >= w4(f / 100)[2]), None, "snowmobile")
    z4, g4, r4 = w4(v["w4.wheel_share"])
    put("w4.wheel_sink_cm", round(z4 * 100, 1), "cm", "snowmobile")
    put("w4.grip_n", round(g4), "N", "snowmobile")
    put("w4.resistance_n", round(r4), "N", "snowmobile")
    put("w4.resistance_bekker_n", round(w4(v["w4.wheel_share"], bekker_res=True)[2]), "N", "snowmobile")
    # the pan's own sinkage under the rest of the weight; the tyres must reach that much deeper
    z_pan = bekker((1 - v["w4.wheel_share"]) * w4w / (hl * hb) / 1000, v["hull.beam_mm"]) / 100
    put("w4.wheel_drop_mm", round((z4 - z_pan) * 1000), "mm", "snowmobile")
    put("w4.tyre_dia_min_mm", round(2 * z4 * 1000), "mm", "snowmobile")
    # W4 with a second tyre bolted outside each rear tyre in winter, like a tractor's duals
    zd, gd, rd = w4(v["w4.wheel_share"], 4)
    put("w4.dual_share_min", next(f / 100 for f in range(5, 100, 5) if w4(f / 100, 4)[1] >= w4(f / 100, 4)[2]), None,
        "snowmobile")
    put("w4.dual_wheel_sink_cm", round(zd * 100, 1), "cm", "snowmobile")
    put("w4.dual_grip_n", round(gd), "N", "snowmobile")
    put("w4.dual_resistance_bekker_n", round(w4(v["w4.wheel_share"], 4, bekker_res=True)[2]), "N", "snowmobile")
    # large low-pressure tyres instead, two and four
    for tag, n_t in (("big", 2), ("big_dual", 4)):
        zb, gb, rb = w4(v["w4.wheel_share"], n_t, v["w4.big_tyre_dia_mm"], v["w4.big_tyre_width_mm"], True)
        put(f"w4.{tag}_wheel_sink_cm", round(zb * 100, 1), "cm", "snowmobile")
        put(f"w4.{tag}_grip_n", round(gb), "N", "snowmobile")
        put(f"w4.{tag}_resistance_bekker_n", round(rb), "N", "snowmobile")
    put("w4.dual_width_m", round(v["lay.track_rear_mm"] / 1000 + 3 * v["yr.rear_width_mm"] / 1000 + 0.02, 2), "m", "snowmobile")

    # Straddle kart (D-030, 1.2.18): the adult astride a seat over the engine; the static ratios
    # of half the track and half the wheelbase over the centre of mass, and its size
    m_k, m_r = v["st.kart_mass_kg"], v["rider.mass_max_kg"]
    h_r = v["st.seat_height_mm"] / 1000 + v["rider.cg_above_seat_m"]
    h_st = (m_k * v["st.kart_cg_mm"] / 1000 + m_r * h_r) / (m_k + m_r)
    put("st.cg_height_m", round(h_st, 3), "m", "straddle")
    put("st.tip_ratio", round(v["st.track_mm"] / 2000 / h_st, 2), None, "straddle")
    # the rider sits about the middle; the shorter of the two pitch arms sets the ratio
    x_cg = (m_k * v["st.kart_cg_x_share"] + m_r * 0.5) / (m_k + m_r) * v["st.wheelbase_mm"] / 1000
    put("st.pitch_ratio", round(min(x_cg, v["st.wheelbase_mm"] / 1000 - x_cg) / h_st, 2), None, "straddle")
    put("st.length_m", round((v["st.wheelbase_mm"] + 2 * v["st.overhang_mm"]) / 1000, 2), "m", "straddle")
    put("st.width_m", round((v["st.track_mm"] + v["whl.tyre_width_mm"] + 2 * v["st.fender_mm"]) / 1000, 2), "m", "straddle")
    # a child fits if, standing on the footrests, the crotch clears the seat by rider.child_fit_clear_mm (P69)
    crotch = v["rider.child_crotch_ratio"] * v["rider.stature_min_cm"] * 10
    put("st.child_fit_margin_mm", round(crotch - (v["st.seat_height_mm"] - v["st.footrest_height_mm"])
                                        - v["rider.child_fit_clear_mm"]), "mm", "straddle")

    # Ideas from the MTT (1.2.17), on the snowmobile form W3: towing a sled on level packed snow -
    # the track's grip less its own resistance is the pull, and a polyethylene sled starts at
    # sled.cold_start_factor times its steady resistance - and new snowblower crawlers in place
    # of the donor's track, looped over two wheels
    wt3 = (m_w + v["rider.mass_max_kg"]) * G
    pull = v["snow.track_traction_packed"] * wt3 * share - v["track.crr_snow_packed"] * wt3
    put("mtt.tow_pull_packed_n", round(pull), "N", "mtt")
    m_sled = pull / (v["sled.mu_packed"] * v["sled.cold_start_factor"] * G)
    put("mtt.tow_sled_kg", round(m_sled), "kg", "mtt")
    put("mtt.tow_power_kw", round((v["track.crr_snow_packed"] * wt3 + v["sled.mu_packed"] * m_sled * G)
                                  * v["sm.speed_snow_kmh"] / 3.6 / v["drive.efficiency"] / 1000, 2), "kW", "mtt")
    dw = v["sm.crawler_wheel_dia_mm"] / 1000
    for tag, n_c in (("crawler180_pair", 2), ("crawler300", 1), ("crawler300_pair", 2)):
        c = tag.split("_")[0].replace("crawler", "crawler.c")
        lc = (v[c + "_pitch_mm"] / 1000 * v[c + "_links"] - math.pi * dw) / 2
        put(f"mtt.{tag}_kpa", round(wt3 * share / (n_c * v[c + "_width_mm"] / 1000 * lc) / 1000, 1), "kPa", "mtt")

    # Tyres all year, skis beside the front wheels, and one front wheel (1.2.19), on the straddle
    # kart of 1.3: buggy-size tyres lift the chassis by the radius difference
    h_a, rs_a, wb_a = v["dsn.cg_height_adult_m"], v["dsn.rear_share_adult"], v["lay.wheelbase_mm"] / 1000
    x_a = (1 - rs_a) * wb_a
    w_a = (v["dsn.mass_kg"] + v["rider.mass_max_kg"]) * G
    d_y, b_yr, b_yf = v["yr.tyre_dia_mm"] / 1000, v["yr.rear_width_mm"] / 1000, v["yr.front_width_mm"] / 1000
    # the design carries these tyres since D-032, so its centre of mass already includes their lift
    # over the 13 in tyres of 1.4; the widest track fits both the road and the car's opening
    lift_y = d_y / 2 - v["whl.tyre_od_mm"] / 2000
    h_y = h_a
    t_y = min(v["law.width_max_mm"], v["delica.opening_width_max_mm"]) / 1000 - b_yr - 2 * v["lay.fender_margin_mm"] / 1000
    put("yr.lift_mm", round(lift_y * 1000), "mm", "tyres")
    put("yr.track_max_mm", round(t_y * 1000), "mm", "tyres")
    put("yr.tip_ratio", round(t_y / 2 / h_y, 2), None, "tyres")
    put("yr.pitch_ratio", round(min(x_a, wb_a - x_a) / h_y, 2), None, "tyres")
    put("yr.length_m", round(max(wb_a + v["lay.front_overhang_mm"] / 1000, wb_a + d_y / 2)
                             - min(-v["lay.rear_overhang_mm"] / 1000, -d_y / 2), 2), "m", "tyres")
    # the winter tyres of W5 kept all year, against these
    d5 = v["w5.tyre_dia_mm"] / 1000
    put("w5.pitch_ratio_all_year", round(min(x_a, wb_a - x_a) / (h_a + (d5 - d_y) / 2), 2), None, "tyres")
    put("w5.length_all_year_m", round(wb_a + d5, 2), "m", "tyres")

    def rut(load, d, b):   # Bekker's wheel sinkage and the work of pressing its rut, worst snow
        best = None
        for s_ in "abc":
            n_, kc, kp = v[f"snow.bekker_{s_}_n"], v[f"snow.bekker_{s_}_kc"], v[f"snow.bekker_{s_}_kphi"]
            z_ = (3 * load / ((3 - n_) * (kc + b * kp) * 1000 * math.sqrt(d))) ** (2 / (2 * n_ + 1))
            if best is None or z_ > best[0]:
                best = (z_, b * (kc / b + kp) * 1000 * z_ ** (n_ + 1) / (n_ + 1))
        return best
    # in fresh snow: a front tyre against a ski carrying the same load
    load_f = w_a * (1 - rs_a) / 2
    z_f, r_f = rut(load_f, d_y, b_yf)
    put("yr.front_tyre_sink_cm", round(z_f * 100, 1), "cm", "tyres")
    put("yr.front_tyre_resist_n", round(r_f), "N", "tyres")
    b_s, l_s = v["ski.width_mm"] / 1000, v["ski.contact_length_mm"] / 1000
    p_s = load_f / (b_s * l_s) / 1000
    s_w = max("abc", key=lambda s_: (p_s / (v[f"snow.bekker_{s_}_kc"] / b_s + v[f"snow.bekker_{s_}_kphi"])) ** (1 / v[f"snow.bekker_{s_}_n"]))
    n_s, k_s = v[f"snow.bekker_{s_w}_n"], v[f"snow.bekker_{s_w}_kc"] / b_s + v[f"snow.bekker_{s_w}_kphi"]
    z_s = (p_s / k_s) ** (1 / n_s)
    put("yr.ski_sink_cm", round(z_s * 100, 1), "cm", "tyres")
    put("yr.ski_resist_n", round(b_s * k_s * 1000 * z_s ** (n_s + 1) / (n_s + 1) + v["sled.mu_packed"] * load_f), "N", "tyres")
    # the rear tyres pushing with skis in front: their grip against their ruts
    z_r, r_r = rut(w_a * rs_a / 2, d_y, b_yr)
    arc = min(math.sqrt(d_y * z_r), d_y / 2)
    n_c = w_a * rs_a / 2 / (b_yr * arc) / 1000
    put("yr.rear_grip_n", round(2 * v["snow.crrel_trac_shallow_a"] * n_c ** v["snow.crrel_trac_shallow_b"] * b_yr * arc * 1000), "N", "tyres")
    put("yr.rear_resist_n", round(2 * r_r), "N", "tyres")
    # skis beside the front wheels: the stance inside or outside them, and the sideways ratio
    for tag, sgn in (("inside", -1), ("outside", 1)):
        y_ski = t_y / 2 + sgn * (b_yf / 2 + 0.03 + b_s / 2)
        half = t_y / 2 + (y_ski - t_y / 2) * (x_a / wb_a)
        put(f"yr.ski_{tag}_tip_ratio", round(half / h_y, 2), None, "tyres")
    # one front wheel: the tipping edge runs from it to a rear wheel
    a_t = t_y / 2
    put("tri.tip_ratio", round(a_t * (1 - x_a / wb_a) / math.hypot(1, a_t / wb_a) / h_a, 2), None, "tyres")
    # the highest centre of mass at which some place meets both the sideways and the fore-and-aft margin
    k_side, k_pitch = v["kart.tip_ratio_snow_min"], v["law.quad_pitch_ratio_min"]
    h_ok = max(hh / 1000 for hh in range(300, 700)
               if k_pitch * hh / 1000 <= wb_a * (1 - k_side * hh / 1000 * math.hypot(1, a_t / wb_a) / a_t))
    put("tri.cg_height_max_m", round(h_ok, 2), "m", "tyres")

    # Winter parts: a running donor for its rear half, skis, mounts, and the tub
    tub = (bottom * v["cost.hull_bottom_jpy_per_m2"] + sides * v["cost.hull_side_jpy_per_m2"]
           + foam * v["cost.xps_jpy_per_m3"])
    put("cost.tub_jpy", round(tub), "JPY", "water")
    put("cost.winter_sm_jpy", round(v["cost.donor_bravo_jpy"] + v["cost.allow_skis_jpy"]
                                    + v["cost.allow_winter_mounts_jpy"] + tub), "JPY", "snowmobile")

    # Cost
    frame = (v["frame.tube_25_m"] * v["cost.tube_25_jpy_per_m"]
             + v["frame.tube_32_m"] * v["cost.tube_32_jpy_per_m"] + v["cost.allow_shipping_jpy"])
    chassis = (frame + v["cost.axle_kit_jpy"] + v["cost.steering_kit_jpy"] + v["cost.tyres_set_jpy"]
               + v["cost.seat_jpy"] + v["cost.allow_small_parts_jpy"] + v["cost.allow_controls_jpy"]
               + v["cost.allow_guards_mounts_jpy"])
    put("cost.chassis_jpy", round(chassis), "JPY", "cost")
    engine_drive = v["cost.clutch_jpy"] + v["cost.allow_reduction_jpy"] + v["cost.allow_drive_chains_jpy"]
    put("cost.power_engine_clone_jpy", round(v["cost.engine_clone_jpy"] + engine_drive), "JPY", "cost")
    put("cost.power_engine_genuine_jpy", round(v["cost.engine_genuine_jpy"] + engine_drive), "JPY", "cost")
    electric = v["cost.allow_electric_jpy"] + v["cost.allow_drive_chains_jpy"]
    put("cost.power_electric_jpy", round(v["cost.motor_kit_jpy"] + 4 * v["cost.battery_12v_jpy"]
                                         + v["cost.charger_jpy"] + electric), "JPY", "cost")
    put("cost.power_electric2_jpy", round(v["cost.motor2_kit_jpy"] + v["cost.battery_48v_jpy"]
                                          + v["cost.charger_48v_jpy"] + electric), "JPY", "cost")
    put("cost.winter_skis_chains_jpy", round(v["cost.allow_skis_jpy"] + 2 * v["cost.snow_chain_jpy"]), "JPY", "cost")
    put("cost.winter_tracks_jpy", round(v["cost.allow_skis_jpy"] + 2 * v["cost.track_jpy"]
                                        + v["cost.allow_track_gear_jpy"]), "JPY", "cost")
    base = chassis + v["cost.engine_clone_jpy"] + engine_drive
    put("cost.total_l2_e1_w1_jpy", round(base + v["cost.allow_skis_jpy"] + 2 * v["cost.snow_chain_jpy"]), "JPY", "cost")
    put("cost.total_l2_e1_w2_jpy", round(base + v["cost.allow_skis_jpy"] + 2 * v["cost.track_jpy"]
                                         + v["cost.allow_track_gear_jpy"]), "JPY", "cost")
    # Cheaper routes, both with W1: the cheapest new parts seen, and a used buggy as donor
    # of axle, hubs, brake, wheels, steering, and engine with its gearbox
    common = (frame + v["cost.allow_small_parts_jpy"] + v["cost.allow_controls_jpy"]
              + v["cost.allow_guards_mounts_jpy"] + v["cost.allow_skis_jpy"] + 2 * v["cost.snow_chain_jpy"])
    cheap = (common + v["cost.axle_parts_cheap_jpy"] + v["cost.steering_cheap_jpy"]
             + 4 * v["cost.tyre_each_cheap_jpy"] + v["cost.brake_cheap_jpy"] + v["cost.seat_cheap_jpy"]
             + v["cost.engine_clone_jpy"] + engine_drive)
    put("cost.total_cheap_new_w1_jpy", round(cheap), "JPY", "cost")
    # A donor's axle is narrower than R-12 asks and does not let the track narrow (T1), so a new
    # axle with hubs and a brake is added; the donor's own engine and gearbox are kept (K-003)
    axle = v["cost.axle_parts_cheap_jpy"] + v["cost.brake_cheap_jpy"]
    put("cost.total_donor_min_w1_jpy", round(common + v["cost.seat_cheap_jpy"] + v["cost.donor_buggy_running_min_jpy"] + axle),
        "JPY", "cost")
    put("cost.total_donor_w1_jpy", round(common + v["cost.seat_cheap_jpy"] + v["cost.donor_buggy_max_jpy"] + axle), "JPY", "cost")
    put("cost.total_donor_e1_w1_jpy", round(common + v["cost.seat_cheap_jpy"] + v["cost.donor_buggy_running_min_jpy"] + axle
                                            + v["cost.engine_clone_jpy"] + engine_drive), "JPY", "cost")
    # The least kart: a running donor's axle and wheels as they are, the owner's frame, no winter parts
    put("cost.total_donor_narrow_summer_jpy", round(common - v["cost.allow_skis_jpy"] - 2 * v["cost.snow_chain_jpy"]
                                                    + v["cost.seat_cheap_jpy"] + v["cost.donor_buggy_running_min_jpy"]),
        "JPY", "cost")
    return out


def as_yaml(out):
    lines = [BEGIN]
    for key, val, unit, sec in out:
        lines += [f"  - key: {key}", f"    v: {val}"]
        if unit:
            lines.append(f"    unit: {unit}")
        lines += ["    status: calculated", "    basis:", f"      - docs/02-form.md#{sec}"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    out = compute(values())
    for key, val, unit, _ in out:
        print(f"{key:34s} {val} {unit or ''}")
    if "--write" in sys.argv:
        p = ROOT / "record" / "values.yaml"
        text = p.read_text(encoding="utf-8")
        block = as_yaml(out)
        if BEGIN in text:
            head, rest = text.split(BEGIN + "\n", 1)
            tail = rest.split(END + "\n", 1)[1]
            text = head + block + tail
        else:
            text = text.rstrip("\n") + "\n" + block
        p.write_text(text, encoding="utf-8", newline="\n")
        print("wrote record/values.yaml")


if __name__ == "__main__":
    main()
