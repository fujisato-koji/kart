"""Design calculation of step 1.3: layout, frame, parts, mass, and checks.

Reads every input from record/values.yaml (the design choices of docs/03-design.md, the
parts' catalogue data, and the assumptions of Q-017), and writes:
- the calculated values back into record/values.yaml between its own markers, and
- docs/data/design.json, the geometry the navigator's drawings and 3D view draw.

    python calc/design.py          # print
    python calc/design.py --write  # also write the record and design.json
    python calc/design.py --check  # fail if design.json is not what would be written

Axes: x forward, y left, z up, in metres; origin on the ground under the rear axle centre.
"""
import importlib.util
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("tdr", ROOT / "tools" / "tdr.py")
tdr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tdr)

OUT = ROOT / "docs" / "data" / "design.json"
BEGIN = "  # begin: generated by calc/design.py"
END = "  # end: generated by calc/design.py"
G = 9.81
CONFIGS = ["summer", "winter", "transport", "water"]
WHEELED = ["summer", "transport", "water"]
RHO_W = 1000  # fresh water, kg/m3


def values():
    rec = tdr.Record(ROOT)
    return {it.d["key"]: it.d["v"] for it in rec.items["value"]}


def build(v):
    mm = lambda k: v[k] / 1000.0
    out = []          # calculated values: (key, value, unit, section)
    items = []        # drawn items
    members = []      # frame tubes

    def put(key, val, unit, sec):
        out.append((key, val, unit, sec))

    def item(part, typ, configs=None, **kw):
        d = {"part": part, "type": typ, "configs": configs or CONFIGS}
        d.update({k: (round(x, 4) if isinstance(x, float) else x) for k, x in kw.items()})
        items.append(d)

    def rnd(p):
        return [round(c, 4) for c in p]

    # ---- layout --------------------------------------------------------------------------
    wb = mm("lay.wheelbase_mm")
    tf, tr, trn = mm("lay.track_front_mm"), mm("lay.track_rear_mm"), mm("lay.track_rear_narrow_mm")
    tyre_d, tyre_w = mm("whl.tyre_od_mm"), mm("whl.tyre_width_mm")
    r = tyre_d / 2
    zr = mm("lay.rail_bottom_mm")
    rail_od, rail_t = mm("dsn.rail_od_mm"), mm("dsn.rail_t_mm")
    cross_od, cross_t = mm("dsn.cross_od_mm"), mm("dsn.cross_t_mm")
    zc = zr + rail_od / 2                      # rail centre line height
    yr, yf = mm("lay.rail_half_width_mm"), mm("lay.front_half_width_mm")
    xf, xb = wb + mm("lay.front_overhang_mm"), -mm("lay.rear_overhang_mm")
    length = xf - xb
    put("dsn.length_m", round(length, 3), "m", "layout")
    width = max(tf, tr) + tyre_w
    put("dsn.width_m", round(width, 3), "m", "layout")
    width_t = max(tf + tyre_w, trn + tyre_w, mm("lay.axle_length_mm"))  # the axle ends stick out when narrowed
    put("dsn.width_transport_m", round(width_t, 3), "m", "transport")

    # ---- rear axle position and bearings (sizes needed by the frame) ---------------------------
    da = mm("dsn.axle_dia_mm")
    La = mm("lay.axle_length_mm")
    yb, ybm = mm("lay.bearing_y_mm"), mm("lay.bearing_mid_y_mm")
    h205, l205, h2_205 = mm("brg.ucp205_h_mm"), mm("brg.ucp205_l_mm"), mm("brg.ucp205_h2_mm")
    # The bearings hang upside down under plates; the rear rails rise over the axle to them
    z_bplate = r + h205                                 # top of the bearing base
    zc_hi = z_bplate + 0.006 + rail_od / 2              # centre of the raised rear rails
    put("dsn.axle_rail_gap_mm", round((zc_hi - rail_od / 2 - (r + da / 2)) * 1000), "mm", "frame")
    xk = mm("lay.kick_x_mm")

    # ---- frame -----------------------------------------------------------------------------
    # Two main rails low under the driver, rising behind x = kick to pass over the rear axle,
    # cross members, outriggers to the outer axle bearings, a seat back hoop, a front bumper,
    # side nerf bars (R-13; the left one only ahead of the engine), and a column support.
    xh_, yh_ = mm("lay.hpoint_x_mm"), mm("lay.hpoint_y_mm")
    xw_, zw_ = mm("lay.wheel_x_mm"), mm("lay.wheel_z_mm")
    x_colsup = 0.75
    z_colsup = zw_ - (x_colsup - xw_) / (wb - 0.05 - xw_) * (zw_ - (zc + 0.04))
    N = {
        "rl0": (xb + 0.03, yr, zc_hi), "rr0": (xb + 0.03, -yr, zc_hi),
        "rlk": (0.10, yr, zc_hi), "rrk": (0.10, -yr, zc_hi),
        "rl1": (xk, yr, zc), "rr1": (xk, -yr, zc),
        "rl2": (0.55, yr, zc), "rr2": (0.55, -yr, zc),
        "rl3": (0.75, yr, zc), "rr3": (0.75, -yr, zc),
        "fl": (wb, yf, zc + 0.02), "fr": (wb, -yf, zc + 0.02),
        "fl2": (wb + 0.12, yr * 0.7, zc), "fr2": (wb + 0.12, -yr * 0.7, zc),
        "bl": (xf - 0.02, yr * 0.75, zc + 0.10), "br": (xf - 0.02, -yr * 0.75, zc + 0.10),
        "ol0": (-0.09, yr, zc_hi), "ol1": (-0.09, yb + 0.03, zc_hi), "ol2": (0.09, yb + 0.03, zc_hi), "ol3": (0.09, yr, zc_hi),
        "or0": (-0.09, -yr, zc_hi), "or1": (-0.09, -yb - 0.03, zc_hi), "or2": (0.09, -yb - 0.03, zc_hi), "or3": (0.09, -yr, zc_hi),
        "hb_lb": (xh_ - 0.13, yh_ + 0.19, zc_hi), "hb_rb": (xh_ - 0.13, yh_ - 0.19, zc_hi),
        "hb_l": (xh_ - 0.17, yh_ + 0.19, mm("lay.rollbar_top_mm") - rail_od / 2),
        "hb_r": (xh_ - 0.17, yh_ - 0.19, mm("lay.rollbar_top_mm") - rail_od / 2),
        "nl0": (0.62, yr, zc), "nl1": (0.70, yr + 0.12, zc + 0.04),
        "nr0": (0.20, -yr - 0.17, zc + 0.04), "nr1": (0.70, -yr - 0.12, zc + 0.04),
        "col0": (x_colsup, yh_, zc), "col1": (x_colsup, yh_, z_colsup),
    }
    main = [("rl0", "rlk"), ("rlk", "rl1"), ("rl1", "rl2"), ("rl2", "rl3"), ("rl3", "fl"), ("fl", "fl2"), ("fl2", "bl"),
            ("rr0", "rrk"), ("rrk", "rr1"), ("rr1", "rr2"), ("rr2", "rr3"), ("rr3", "fr"), ("fr", "fr2"), ("fr2", "br")]
    cross = [("rl0", "rr0"), ("rl1", "rr1"), ("rl2", "rr2"), ("rl3", "rr3"), ("fl", "fr"), ("fl2", "fr2"), ("bl", "br"),
             ("ol0", "ol1"), ("ol1", "ol2"), ("ol2", "ol3"), ("or0", "or1"), ("or1", "or2"), ("or2", "or3"),
             ("hb_lb", "hb_l"), ("hb_l", "hb_r"), ("hb_r", "hb_rb"), ("hb_lb", "hb_rb"), ("hb_l", "rl0"), ("hb_r", "rr0"),
             ("nl0", "nl1"), ("nl1", "rl3"), ("rr1", "nr0"), ("nr0", "nr1"), ("nr1", "rr3"),
             ("col0", "col1"), ("rl3", "col1"), ("rr3", "col1")]
    tube_len = {"main": 0.0, "cross": 0.0, "roll": 0.0}
    for a, b in main:
        members.append({"part": "frame", "a": rnd(N[a]), "b": rnd(N[b]), "od": rail_od, "t": rail_t})
        tube_len["main"] += math.dist(N[a], N[b])
    for a, b in cross:
        part = "bumpers" if a[0] == "n" or b[0] == "n" or a == "bl" else "frame"
        if a.startswith("hb") or b.startswith("hb"):
            part = "roll_bar"
        od_, t_ = (rail_od, rail_t) if part == "roll_bar" else (cross_od, cross_t)
        members.append({"part": part, "a": rnd(N[a]), "b": rnd(N[b]), "od": od_, "t": t_})
        tube_len["roll" if part == "roll_bar" else "cross"] += math.dist(N[a], N[b])
    put("dsn.tube_main_m", round(tube_len["main"], 2), "m", "frame")
    put("dsn.tube_cross_m", round(tube_len["cross"], 2), "m", "frame")
    put("dsn.tube_roll_m", round(tube_len["roll"], 2), "m", "rollbar")
    rho = v["dsn.steel_density_kg_m3"]
    tube_mass = lambda od_, t_, L: rho * math.pi * (od_ * od_ - (od_ - 2 * t_) ** 2) / 4 * L
    m_frame = tube_mass(rail_od, rail_t, tube_len["main"]) + tube_mass(cross_od, cross_t, tube_len["cross"])
    # the floor covers the driver side only, clear of the drive on the left
    fx0, fx1, fy0, fy1 = 0.10, 0.90, -yr + 0.02, yh_ + 0.19
    m_floor = rho * (fx1 - fx0) * (fy1 - fy0) * mm("dsn.floor_t_mm")
    item("floor", "plate", pos=[(fx0 + fx1) / 2, (fy0 + fy1) / 2, zr - 0.002], size=[fx1 - fx0, fy1 - fy0, v["dsn.floor_t_mm"] / 1000])

    # ---- masses and centre of mass ---------------------------------------------------------
    masses = []   # (part, kg, (x, y, z))

    def mass(part, kg, pos):
        masses.append((part, kg, pos))

    mass("frame", m_frame, (0.45, 0.0, zc + 0.05))
    m_roll = tube_mass(rail_od, rail_t, tube_len["roll"])
    mass("roll_bar", m_roll, (xh_ - 0.12, yh_, (zc_hi + mm("lay.rollbar_top_mm")) / 2))
    mass("floor", m_floor, ((fx0 + fx1) / 2, (fy0 + fy1) / 2, zr))

    # ---- rear axle, hubs, wheels, bearings, brake --------------------------------------------
    item("axle_shaft", "cyl", configs=WHEELED, pos=[0.0, 0.0, r], axis="y", d=da, l=La)
    mass("axle_shaft", rho * math.pi * da * da / 4 * La, (0.0, 0.0, r))
    plates = 0.0
    for yy in (yb, ybm, -yb):
        item("axle_bearings", "pillow", pos=[0.0, yy, z_bplate], h=h205, l=l205, h2=h2_205, bore=da, axis="y", inverted=True)
        mass("axle_bearings", v["brg.ucp205_mass_kg"], (0.0, yy, r))
        item("frame", "plate", pos=[0.0, yy, z_bplate + 0.003], size=[0.20, 0.07, 0.006])
        plates += rho * 0.20 * 0.07 * 0.006
    low_bearing = r - (h2_205 - h205)
    for cfg in WHEELED:
        t_ = trn if cfg == "transport" else tr
        for s in (1, -1):
            item("rear_hubs", "hub", configs=[cfg], pos=[0.0, s * (t_ / 2 - 0.02), r], axis="y", d=0.07, l=0.05)
            item("rear_wheels", "wheel", configs=[cfg], pos=[0.0, s * t_ / 2, r], axis="y", od=tyre_d, width=tyre_w,
                 rim=0.152)
    put("dsn.hub_bearing_gap_mm", round((trn / 2 - tyre_w / 2 - (yb + 0.0171)) * 1000), "mm", "transport")
    for s in (1, -1):
        mass("rear_wheels", v["dsn.wheel_mass_kg"], (0.0, s * tr / 2, r))
        mass("rear_hubs", 0.8, (0.0, s * (tr / 2 - 0.02), r))
    dd = mm("lay.disc_dia_mm")
    yd = mm("lay.brake_y_mm")
    item("brake", "disc", configs=WHEELED, pos=[0.0, yd, r], axis="y", d=dd, t=0.004)
    item("brake", "caliper", configs=WHEELED, pos=[0.0, yd, r + dd / 2 - 0.02], size=[0.06, 0.04, 0.05])
    mass("brake", v["dsn.brake_mass_kg"], (0.0, yd, r))
    low_disc = r - dd / 2

    # ---- powertrain: a 50 cc scooter's engine unit and one chain of size 420 ------------------
    # The unit (engine, CVT, centrifugal clutch, final reduction) sits beside the seat on the
    # left, its output shaft at the rear end pointing toward the seat; a 420 chain runs from the
    # output sprocket to the axle sprocket beside the middle axle bearing. Slotted holes under
    # the unit's mounting plate tension the chain.
    p420 = 0.0127
    t_out, t4 = v["gear.t_out420"], v["gear.t_axle420"]
    pd_out = p420 / math.sin(math.pi / t_out)
    pd_ax = p420 / math.sin(math.pi / t4)
    pd, od = {t4: pd_ax}, {t4: pd_ax + 0.6 * p420}
    chain_r = t4 / t_out
    ratio_top = v["eng50.cvt_high"] * v["su.final_ratio"] * chain_r
    ratio = v["eng50.cvt_low"] * v["su.final_ratio"] * chain_r   # lowest overall ratio, for climbing and the chain pull
    put("dsn.ratio_top", round(ratio_top, 2), None, "drive")
    put("dsn.ratio", round(ratio, 2), None, "drive")
    v_top = v["su.rev_limit_rpm"] / ratio_top / 60 * math.pi * tyre_d * 3.6
    put("dsn.top_speed_kmh", round(v_top, 2), "km/h", "drive")
    ul, uw, uh = mm("su.length_mm"), mm("su.width_mm"), mm("su.height_mm")
    yu, y2 = mm("lay.unit_y_mm"), mm("lay.chain420_y_mm")
    x_out = mm("lay.unit_out_x_mm")
    z_base = zr + rail_od + 0.006                      # unit plate on the rails
    z_out = z_base + uh * 0.35                         # output shaft height in the unit (Q-023)
    eh = uh
    xe, ye = x_out - 0.05 + ul / 2, yu
    item("frame", "plate", pos=[xe, yu, z_base - 0.003], size=[ul * 0.8, uw * 0.8, 0.006])
    plates += rho * ul * 0.8 * uw * 0.8 * 0.006
    item("engine", "scooter_unit", pos=[xe, yu, z_base], length=ul, width=uw, height=uh, out=[x_out, y2 + 0.025, z_out],
         cylinder="+x")
    mass("engine", v["su.mass_kg"], (xe, yu, z_base + uh * 0.45))
    mass("fuel", v["dsn.fuel_mass_kg"], (xe + ul * 0.15, yu, z_base + uh * 0.9))
    mass("frame", plates, (0.2, 0.2, zc))
    item("chain_final", "sprocket", pos=[x_out, y2, z_out], axis="y", teeth=t_out, pd=pd_out, od=pd_out + 0.6 * p420, t=0.006)
    item("chain_final", "sprocket", configs=WHEELED, pos=[0.0, y2, r], axis="y", teeth=t4, pd=pd_ax, od=od[t4], t=0.006)
    c420 = math.dist((x_out, z_out), (0.0, r))
    exact = 2 * c420 / p420 + (t_out + t4) / 2 + p420 * (t4 - t_out) ** 2 / (4 * math.pi ** 2 * c420)
    put("dsn.chain420_centre_mm", round(c420 * 1000), "mm", "drive")
    put("dsn.chain420_links", math.ceil(exact / 2) * 2, None, "drive")
    put("dsn.unit_front_x_mm", round((xe + ul / 2) * 1000), "mm", "drive")
    item("chain_final", "chain", configs=WHEELED, pos=[x_out, y2, z_out], to=[0.0, y2, r], r1=pd_out / 2, r2=pd_ax / 2,
         axis="y")
    mass("chain_final", 1.1, (x_out / 2, y2, (z_out + r) / 2))
    low_spr = r - od[t4] / 2
    item("guards", "guard", configs=WHEELED, pos=[x_out / 2, y2 - 0.035, (z_out + r) / 2 + 0.02],
         size=[x_out + 0.12, 0.004, 0.17])
    mass("guards", 1.2, (x_out / 2, y2 - 0.035, r + 0.05))

    # lowest parts under the rear axle (R-04: only the tyres touch the ground)
    low = min(low_bearing, low_disc, low_spr, zr)
    put("dsn.low_point_mm", round(low * 1000), "mm", "axle")

    # ---- front: spindles, wheels, skis -------------------------------------------------------
    for s in (1, -1):
        king = (wb, s * yf, zc + 0.02)
        item("spindles", "spindle", pos=rnd(king), side=s, to=[wb, s * tf / 2, r], arm=0.09)
        mass("spindles", 1.2, (wb, s * (yf + tf / 2) / 2, r))
        for cfg in WHEELED:
            item("front_wheels", "wheel", configs=[cfg], pos=[wb, s * tf / 2, r], axis="y", od=tyre_d, width=tyre_w,
                 rim=0.152)
        mass("front_wheels", v["dsn.wheel_mass_kg"], (wb, s * tf / 2, r))

    # ---- steering ----------------------------------------------------------------------------
    xw, zw = mm("lay.wheel_x_mm"), mm("lay.wheel_z_mm")
    yw = mm("lay.hpoint_y_mm")
    item("steering_column", "rod", pos=[xw, yw, zw], to=[wb - 0.05, yw, zc + 0.04], d=0.020)
    item("steering_wheel", "steering_wheel", pos=[xw - 0.02, yw, zw + 0.01], d=0.30, tilt_deg=60)
    for s in (1, -1):
        item("tie_rods", "rod", pos=[wb - 0.05, yw, zc + 0.04], to=[wb - 0.09, s * (yf - 0.02), zc + 0.03], d=0.010)
    mass("steering", v["dsn.steering_mass_kg"], ((xw + wb) / 2, yw, (zw + zc) / 2))
    steer = math.radians(v["lay.steer_max_deg"])
    turn = wb / math.tan(steer) + tf / 2
    put("dsn.turn_radius_m", round(turn, 2), "m", "steering")

    # ---- seat, pedals, riders ----------------------------------------------------------------
    xh, yh = mm("lay.hpoint_x_mm"), mm("lay.hpoint_y_mm")
    slide = mm("lay.seat_slide_mm")
    z_seat = zr + rail_od + 0.03
    item("seat", "seat", pos=[xh - 0.10, yh, z_seat], w=0.38, l=0.42, h=0.50)
    item("seat_slide", "plate", pos=[xh, yh, zr + rail_od + 0.01], size=[0.30 + slide, 0.30, 0.01])
    mass("seat", v["dsn.seat_mass_kg"], (xh - 0.05, yh, z_seat + 0.15))
    xpf, xpn = mm("lay.pedal_x_far_mm"), mm("lay.pedal_x_near_mm")
    item("pedal_box", "rail", pos=[xpn - 0.05, yh, zr + 0.02], to=[xpf + 0.05, yh, zr + 0.02], d=0.025)
    for cfg_rider, xp in (("adult", xpf), ("child", xpn)):
        item("pedal_box", "pedals", configs=CONFIGS, rider=cfg_rider, pos=[xp, yh, zr + 0.03], spacing=0.14)
    mass("pedal_box", 2.0, ((xpf + xpn) / 2, yh, zr + 0.08))
    mass("misc", v["dsn.misc_mass_kg"], (0.4, 0.0, zc + 0.1))

    # rider positions: the hip (H-point) above the seat, the heel at the pedals
    riders = {}
    for who, stat, mkey, cgk, ratio_k, xp, xshift in (
            ("adult", v["rider.stature_max_cm"] / 100, v["rider.mass_max_kg"], v["rider.cg_above_seat_m"],
             v["dsn.buttock_heel_ratio_adult"], xpf, 0.0),
            ("child", v["rider.stature_min_cm"] / 100, v["rider.mass_child_kg"], v["rider.cg_above_seat_child_m"],
             v["dsn.buttock_heel_ratio_child"], xpn, slide)):
        hip = (xh + xshift, yh, z_seat + 0.06)
        reach = ratio_k * stat
        need = math.dist((hip[0], hip[2]), (xp, zr + 0.10))
        riders[who] = {"stature": stat, "mass": mkey, "hip": rnd(hip), "heel": rnd((xp - 0.02, yh, zr + 0.10)),
                       "leg_reach": round(reach, 3), "leg_needed": round(need, 3), "cg_above_seat": cgk}
        put(f"dsn.leg_margin_{who}_mm", round((reach - need) * 1000), "mm", "fit")

    # ---- road equipment (R-20 to R-24) ------------------------------------------------------
    zt = mm("lay.rollbar_top_mm")
    xbk = xb + 0.03
    item("lighting", "lamp", pos=[xf, 0.0, zc + 0.16], role="head", color="white", facing="+x", d=0.11)
    for s in (1, -1):
        item("lighting", "lamp", pos=[xf - 0.02, s * yr * 0.75, zc + 0.13], role="turn", color="amber", facing="+x", d=0.05)
        item("lighting", "lamp", pos=[xbk - 0.02, s * yr, zc_hi + 0.05], role="turn", color="amber", facing="-x", d=0.05)
        item("mirrors", "mirror", pos=[xh_ - 0.17, yh_ + s * 0.30, zt - 0.12], stem=[xh_ - 0.17, yh_ + s * 0.19, zt - 0.20],
             d=0.10, facing="-x")
    item("lighting", "lamp", pos=[xbk - 0.02, 0.0, zc_hi + 0.07], role="tail_stop", color="red", facing="-x", size=[0.02, 0.12, 0.05])
    item("lighting", "lamp", pos=[xbk - 0.02, 0.0, zc_hi - 0.02], role="reflector", color="red", facing="-x", size=[0.01, 0.06, 0.03])
    item("number_plate", "plate_number", pos=[xbk - 0.03, -0.17, zc_hi + 0.02], size=[0.004, 0.17, 0.10])
    item("lighting", "lamp", pos=[xbk - 0.01, -0.17, zc_hi + 0.09], role="plate", color="white", facing="-z", d=0.03)
    item("horn", "box", pos=[wb + 0.10, 0.0, zc + 0.02], size=[0.06, 0.08, 0.06])
    item("speedometer", "gauge", pos=[xw_ + 0.06, yh_, zw_ + 0.05], d=0.08, facing="-x")
    item("battery", "box", pos=[0.32, -yr + 0.07, zr + rail_od + 0.06], size=[0.11, 0.07, 0.09])
    item("hand_brake", "lever", pos=[xh_ + 0.05, yh_ - 0.25, zc + 0.02], to=[xh_ + 0.05, yh_ - 0.25, zc + 0.30])
    item("hand_brake", "caliper", configs=WHEELED, pos=[0.0, mm("lay.brake_y_mm"), r - mm("lay.disc_dia_mm") / 2 + 0.02],
         size=[0.06, 0.04, 0.05])
    item("head_restraint", "box", pos=[xh_ - 0.15, yh_, zt - 0.17], size=[0.06, 0.22, 0.16])
    hip = (xh_, yh_, zr + rail_od + 0.09)
    for s in (1, -1):
        item("seat_belt", "strap", pos=[hip[0] - 0.05, yh_ + s * 0.20, zc], to=[hip[0] + 0.12, yh_, hip[2] + 0.06], w=0.048)
    item("seat_belt", "strap", pos=[xh_ - 0.17, yh_ + 0.19, zt - 0.25], to=[hip[0] + 0.12, yh_ - 0.12, hip[2] + 0.06], w=0.048)
    mass("road", v["dsn.road_kit_mass_kg"], (0.1, 0.0, zc + 0.2))

    # ---- sled pan (D-023, D-027, D-028): UHMW polyethylene under the frame, kept in both forms --
    # Two bottom strips either side of the track's tunnel and a bow curving up under the front
    # frame. No foam: R-29 asks only for the driver's safety (D-028).
    zp = mm("hull.bottom_clear_mm")
    tb = mm("hull.bottom_t_mm")
    x0, x1 = mm("lay.pan_x0_mm"), mm("lay.pan_x1_mm")
    yt, yo = mm("lay.tunnel_half_width_mm"), mm("lay.pan_half_beam_mm")
    xbw, zbw, ybw = mm("lay.bow_x_mm"), zp + mm("lay.bow_rise_mm"), mm("lay.bow_half_beam_mm")
    sheet_a = 0.0
    for s in (1, -1):
        item("sled_pan", "plate", pos=[(x0 + x1) / 2, s * (yt + yo) / 2, zp + tb / 2], size=[x1 - x0, yo - yt, tb])
        sheet_a += (x1 - x0) * (yo - yt) * tb
    # the bow in three panels, each a flat sheet between two stations (x, half beam, z)
    st = [(x1 + fx * (xbw - x1), yo + fy * (ybw - yo), zp + fz * (zbw - zp))
          for fx, fy, fz in ((0, 0, 0), (0.35, 0.3, 0.1), (0.7, 0.65, 0.4), (1, 1, 1))]
    for (xa, ya, za), (xb_, yb_, zb_) in zip(st, st[1:]):
        item("sled_pan", "sheet", corners=[[xa, ya, za], [xb_, yb_, zb_], [xb_, -yb_, zb_], [xa, -ya, za]], t=tb)
        sheet_a += math.dist((xa, za), (xb_, zb_)) * (ya + yb_) * tb
    bow_area = sum((xb_ - xa) * (ya + yb_) for (xa, ya, _), (xb_, yb_, _) in zip(st, st[1:]))
    m_pan = sheet_a * v["hull.sheet_density_kg_m3"]
    mass("sled_pan", m_pan, ((x0 + xbw) / 2, 0.0, zp + 0.02))
    put("dsn.pan_mass_kg", round(m_pan, 1), "kg", "winter")

    # ---- winter form (D-023, D-025): one centre track from a donor snowmobile, and the skis ----
    # The rear axle with its wheels, hubs, sprocket, and brake disc comes off. The donor's track
    # unit takes its place as one piece: two side plates beside the track carry the skid's cross
    # shafts inside the loop and the drive shaft's bearings, and are held by a pivot shaft through
    # the three pillow blocks at the back and bolted at the front through spacers to the
    # cross members. The track runs under the floor, so the chassis rides higher by dsn.winter_lift_mm,
    # and the skis stand on stanchions as tall. Items marked ground stand on the snow at their
    # own height; the frame and every other item rise by the lift.
    tw, tl, tt = mm("sm.track_width_mm"), mm("sm.track_contact_mm"), mm("sm.track_t_mm")
    xt = mm("sm.track_x_mm")
    d_ds, d_id = mm("sm.drive_dia_mm"), mm("sm.idler_dia_mm")
    x_ds, z_ds = xt + tl / 2 + mm("sm.drive_ahead_mm"), mm("sm.drive_z_mm")
    x_id = xt - tl / 2
    top = z_ds + d_ds / 2 + tt                               # the loop's top, over the drive sprocket
    under = zr - 0.002 - mm("dsn.floor_t_mm") / 2            # the floor's underside, the lowest part over it
    lift = top + mm("lay.tunnel_gap_mm") - under
    put("dsn.winter_lift_mm", round(lift * 1000), "mm", "winter")
    W = ["winter"]
    # the belt's inner face runs on the wheels, its outer face on the snow
    item("track_unit", "track", configs=W, ground=True, width=tw, t=tt,
         wheels=[[x_id, d_id / 2 + tt, d_id / 2], [xt + tl / 2, 0.05 + tt, 0.05], [x_ds, z_ds, d_ds / 2]])
    ys, ysp = tw / 2 - 0.06, tw / 2 + 0.01                   # slide rails; side plates between the track and the chain
    for s in (1, -1):
        item("track_unit", "rail", configs=W, ground=True, pos=[x_id, s * ys, tt + 0.015], to=[xt + tl / 2, s * ys, tt + 0.015],
             d=0.03)
        item("track_unit", "plate", configs=W, ground=True, pos=[(xt - 0.36 + x_ds + 0.06) / 2, s * ysp, (0.09 + under + lift) / 2],
             size=[x_ds + 0.06 - (xt - 0.36), 0.006, under + lift - 0.09])
        # rear lug from the plate's top to just over the pivot shaft, under the seat's slide plate
        lug_top = r + lift + da / 2 + 0.005
        item("track_unit", "plate", configs=W, ground=True, pos=[0.0, s * ysp, (under + lift + lug_top) / 2],
             size=[0.10, 0.006, lug_top - under - lift])
    for xs in (xt - 0.30, xt + 0.30):                         # the skid's cross shafts, inside the loop
        item("track_unit", "cyl", configs=W, ground=True, pos=[xs, 0.0, tt + 0.10], axis="y", d=0.025, l=2 * ysp)
    item("track_unit", "cyl", configs=W, pos=[0.0, 0.0, r], axis="y", d=da, l=2 * yb + 0.06)
    y_disc = ysp + 0.03                                      # the disc and its calipers outside the right plate
    item("track_unit", "cyl", configs=W, ground=True, pos=[x_ds, 0.0, z_ds], axis="y", d=0.03, l=2 * (y_disc + 0.025))
    # the summer brake disc and both calipers move to the drive shaft, opposite the chain
    item("brake", "disc", configs=W, ground=True, pos=[x_ds, -y_disc, z_ds], axis="y", d=dd, t=0.004)
    item("brake", "caliper", configs=W, ground=True, pos=[x_ds, -y_disc, z_ds + dd / 2 - 0.02], size=[0.06, 0.04, 0.05])
    item("hand_brake", "caliper", configs=W, ground=True, pos=[x_ds, -y_disc, z_ds - dd / 2 + 0.02], size=[0.06, 0.04, 0.05])
    # the summer 30T sprocket on the drive shaft, and a longer chain from the engine unit; it
    # crosses the frame's level between the cross members at lay.kick_x_mm and 0.55 m
    item("winter_chain", "sprocket", configs=W, ground=True, pos=[x_ds, y2, z_ds], axis="y", teeth=t4, pd=pd_ax, od=od[t4],
         t=0.006)
    zo_w = z_out + lift
    item("winter_chain", "chain", configs=W, ground=True, pos=[x_out, y2, zo_w], to=[x_ds, y2, z_ds], r1=pd_out / 2,
         r2=pd_ax / 2, axis="y")
    zg0, zg1 = zc + cross_od / 2 + lift + 0.005, zo_w + 0.06   # a guard above the frame, between chain and driver
    item("winter_chain", "guard", configs=W, ground=True, pos=[(x_out - 0.06 + 0.45) / 2, y2 - 0.02, (zg0 + zg1) / 2],
         size=[0.45 - (x_out - 0.06), 0.004, zg1 - zg0])
    cw = math.dist((x_out, zo_w), (x_ds, z_ds))
    exact_w = 2 * cw / p420 + (t_out + t4) / 2 + p420 * (t4 - t_out) ** 2 / (4 * math.pi ** 2 * cw)
    put("dsn.winter_chain_centre_mm", round(cw * 1000), "mm", "winter")
    put("dsn.winter_chain_links", math.ceil(exact_w / 2) * 2, None, "winter")
    for s in (1, -1):
        item("skis", "ski", configs=W, ground=True, pos=[wb, s * tf / 2, 0.0], l=mm("ski.contact_length_mm") * 1.6,
             w=mm("ski.width_mm"), stub_z=r + lift)
    v_w = v["su.rev_limit_rpm"] / ratio_top / 60 * math.pi * d_ds * 3.6
    put("dsn.winter_top_speed_kmh", round(v_w, 1), "km/h", "winter")
    put("dsn.winter_clutch_lock_kmh", round(v["su.clutch_lock_rpm"] / ratio / 60 * math.pi * d_ds * 3.6, 1), "km/h", "winter")

    # ---- future water version (D-027): not required, shown only ----------------------------
    yfl = tr / 2 + tyre_w / 2 + 0.06 + mm("lay.float_dia_mm") / 2
    for s in (1, -1):
        item("side_floats", "float", configs=["water"], future=True, pos=[(xb + xf) / 2, s * yfl, zp + mm("lay.float_dia_mm") / 2],
             l=xf - xb, d=mm("lay.float_dia_mm"))
        item("side_floats", "rod", configs=["water"], future=True, pos=[0.45, s * yr, zc], to=[0.45, s * yfl, zp + 0.15], d=0.025)
    # tilted up, as an outboard stands on land
    item("outboard", "outboard", configs=["water"], future=True, pos=[xb - 0.06, 0.0, zc_hi + 0.10], shaft=0.60, tilt_deg=60)
    item("outboard", "box", configs=["water"], future=True, pos=[xb + 0.12, 0.25, zc_hi + 0.10], size=[0.33, 0.17, 0.22])

    # ---- totals: mass and centre of mass ----------------------------------------------------
    M = sum(m for _, m, _ in masses)
    cx = sum(m * p_[0] for _, m, p_ in masses) / M
    cy = sum(m * p_[1] for _, m, p_ in masses) / M
    cz = sum(m * p_[2] for _, m, p_ in masses) / M
    put("dsn.mass_kg", round(M, 1), "kg", "mass")
    put("dsn.cg_x_m", round(cx, 3), "m", "mass")
    put("dsn.cg_y_m", round(cy, 3), "m", "mass")
    put("dsn.cg_z_m", round(cz, 3), "m", "mass")
    put("dsn.frame_mass_kg", round(m_frame, 1), "kg", "frame")
    for who in ("adult", "child"):
        rd = riders[who]
        mt = M + rd["mass"]
        x_r, y_r, z_r = rd["hip"][0] + 0.10, rd["hip"][1], rd["hip"][2] + rd["cg_above_seat"] - 0.06
        cxt = (M * cx + rd["mass"] * x_r) / mt
        cyt = (M * cy + rd["mass"] * y_r) / mt
        czt = (M * cz + rd["mass"] * z_r) / mt
        rear = 1 - cxt / wb
        # half track at the centre of mass, between the rear and front tracks, less the
        # sideways offset of the centre toward the side it would tip to (the worse side)
        half = tr / 2 + (tf / 2 - tr / 2) * (cxt / wb) - abs(cyt)
        put(f"dsn.rear_share_{who}", round(rear, 3), None, "mass")
        put(f"dsn.cg_side_{who}_mm", round(cyt * 1000), "mm", "mass")
        put(f"dsn.cg_height_{who}_m", round(czt, 3), "m", "mass")
        put(f"dsn.tip_ratio_{who}", round(half / czt, 2), None, "stability")
        if who == "adult":
            m_adult, rear_adult, x_adult = mt, rear, x_r

    # ---- winter totals: the summer masses less the axle, wheels, and summer chain, lifted, plus
    # the parts on the snow; then the adult, the loads on the track and skis, and tipping ------
    gone = {"rear_wheels", "rear_hubs", "axle_shaft", "front_wheels", "brake", "chain_final", "guards"}
    mw = [(pt, m, (p_[0], p_[1], p_[2] + lift)) for pt, m, p_ in masses if pt not in gone]
    mw.append(("track_unit", v["sm.track_unit_kg"], (xt + 0.05, 0.0, (top + tt) / 2)))
    mw.append(("brake", v["dsn.brake_mass_kg"], (x_ds, -y_disc, z_ds)))
    mw.append(("winter_chain", 1.2, ((x_out + 0.45) / 2, y2 - 0.02, (zg0 + zg1) / 2)))     # its guard
    links_s = [x for k_, x, _, _ in out if k_ == "dsn.chain420_links"][0]
    links_w = [x for k_, x, _, _ in out if k_ == "dsn.winter_chain_links"][0]
    mw.append(("winter_chain", 1.1 * links_w / links_s, ((x_out + x_ds) / 2, y2, (zo_w + z_ds) / 2)))
    for s in (1, -1):
        mw.append(("skis", v["ski.pair_kg"] / 2, (wb, s * tf / 2, 0.05)))
        mw.append(("skis", tube_mass(rail_od, rail_t, r + lift), (wb, s * tf / 2, (r + lift) / 2)))   # stanchion
    Mw = sum(m for _, m, _ in mw)
    put("dsn.winter_mass_kg", round(Mw, 1), "kg", "winter")
    rd = riders["adult"]
    xr_, yr_, zr_ = rd["hip"][0] + 0.10, rd["hip"][1], rd["hip"][2] + rd["cg_above_seat"] - 0.06 + lift
    mt = Mw + rd["mass"]
    cxw = (sum(m * p_[0] for _, m, p_ in mw) + rd["mass"] * xr_) / mt
    cyw = (sum(m * p_[1] for _, m, p_ in mw) + rd["mass"] * yr_) / mt
    czw = (sum(m * p_[2] for _, m, p_ in mw) + rd["mass"] * zr_) / mt
    put("dsn.winter_cg_height_m", round(czw, 3), "m", "winter")
    share_w = (wb - cxw) / (wb - xt)
    put("dsn.winter_rear_share", round(share_w, 3), None, "winter")
    wt = mt * G
    put("dsn.winter_track_pressure_kpa", round(wt * share_w / (tw * tl) / 1000, 2), "kPa", "winter")
    put("dsn.winter_ski_pressure_kpa",
        round(wt * (1 - share_w) / (2 * mm("ski.width_mm") * mm("ski.contact_length_mm")) / 1000, 2), "kPa", "winter")

    # three supports: the tipping edge runs from a ski's outer rear corner to the track's rear corner;
    # the centre of mass's distance to it over its height, on the worse side (R-12, D-025)
    def edge(sgn):
        x1_, y1_ = wb - mm("ski.contact_length_mm") / 2, sgn * (tf + mm("ski.width_mm")) / 2
        x2_, y2_ = x_id, sgn * tw / 2
        return abs((y2_ - y1_) * cxw - (x2_ - x1_) * cyw + x2_ * y1_ - y2_ * x1_) / math.hypot(x2_ - x1_, y2_ - y1_)

    put("dsn.winter_tip_ratio", round(min(edge(1), edge(-1)) / czw, 2), None, "stability")
    # when the track sinks that far, the pan's strips and bow meet the snow and, with the track
    # between them, spread the whole weight
    belly = (x1 - x0) * 2 * (yo - yt) + bow_area + tw * tl
    put("dsn.belly_area_m2", round(belly, 2), "m2", "winter")
    put("dsn.belly_pressure_kpa", round(wt / belly / 1000, 2), "kPa", "winter")
    put("dsn.belly_height_mm", round((zp + lift) * 1000), "mm", "winter")

    # ---- climbing the slope on long grass with the adult (R-16) -------------------------------
    th = math.atan(v["site.grade_max_pct"] / 100)
    h_adult = [x for k_, x, _, _ in out if k_ == "dsn.cg_height_adult_m"][0]
    need = m_adult * G * (math.sin(th) + v["ground.crr_max"] * math.cos(th))
    n_rear = m_adult * G * (math.cos(th) * rear_adult + math.sin(th) * h_adult / wb)
    grip = v["ground.mu_grass"] * n_rear
    t_eng = v["eng50.torque_nm"]
    thrust = t_eng * ratio * v["drive.efficiency"] / r
    put("dsn.climb_force_n", round(need), "N", "climb")
    put("dsn.climb_grip_n", round(grip), "N", "climb")
    put("dsn.climb_thrust_n", round(thrust), "N", "climb")

    # ---- strength -----------------------------------------------------------------------------
    k = v["dsn.load_factor"]
    # Axle: a bump on each rear wheel bends it at the outer bearing (wheel load x overhang);
    # the final chain pulls on its sprocket next to the middle bearing at full engine torque.
    # The two act in roughly perpendicular planes and are combined as a vector.
    w_rear = m_adult * G * rear_adult / 2 * k
    arm = tr / 2 - yb
    m_bump = w_rear * arm
    f_chain = t_eng * ratio * v["drive.efficiency"] / (pd[t4] / 2)
    m_chain = f_chain * abs(y2 - ybm)
    m_axle = math.hypot(m_bump, m_chain)
    z_axle = math.pi * da ** 3 / 32
    sigma_axle = m_axle / z_axle / 1e6
    put("dsn.axle_chain_pull_n", round(f_chain), "N", "axle")
    put("dsn.axle_stress_mpa", round(sigma_axle), "MPa", "axle")
    put("dsn.axle_safety", round(v["dsn.s45c_yield_mpa"] / sigma_axle, 2), None, "axle")
    # Frame: the rails as a beam between the rear axle and the kingpins carrying every sprung
    # mass and the rider at their x, times the load factor; half on each rail (the cross
    # members, the floor, and the nerf bars that share the load are left out).
    unsprung = {"rear_wheels", "rear_hubs", "axle_shaft", "axle_bearings", "front_wheels", "spindles", "brake"}
    loads = [(p_[0], m * G * k) for pt, m, p_ in masses if pt not in unsprung]
    loads.append((x_adult, v["rider.mass_max_kg"] * G * k))
    loads = [(min(max(x, 0.0), wb), f) for x, f in loads]
    r_front = sum(f * x for x, f in loads) / wb
    m_max = 0.0
    for i in range(201):
        xs = wb * i / 200
        mom = r_front * (wb - xs) - sum(f * (x - xs) for x, f in loads if x > xs)
        m_max = max(m_max, abs(mom))
    d_in = rail_od - 2 * rail_t
    z_rail = math.pi * (rail_od ** 4 - d_in ** 4) / (32 * rail_od)
    sigma_rail = m_max / 2 / z_rail / 1e6
    put("dsn.frame_moment_nm", round(m_max), "N m", "frame")
    put("dsn.rail_stress_mpa", round(sigma_rail), "MPa", "frame")
    put("dsn.rail_safety", round(v["dsn.stkm11a_tensile_mpa"] / sigma_rail, 2), None, "frame")
    put("dsn.bearing_load_n", round(w_rear / k), "N", "axle")

    # ---- brake --------------------------------------------------------------------------------
    vt = v["kart.speed_max_kmh"] / 3.6
    a_need = vt * vt / (2 * v["kart.stop_distance_max_m"])
    torque = m_adult * a_need * r
    put("dsn.brake_decel_needed", round(a_need, 2), "m/s2", "brake")
    put("dsn.brake_torque_needed_nm", round(torque), "N m", "brake")
    r_eff = dd / 2 - 0.012
    put("dsn.brake_clamp_needed_n", round(torque / (2 * v["dsn.pad_mu"] * r_eff)), "N", "brake")
    # Downhill on the grass slope with rear brakes only: the load moves forward off the rear
    n_rear_dn = m_adult * G * (math.cos(th) * rear_adult - math.sin(th) * h_adult / wb)
    a_dn = v["ground.mu_grass"] * n_rear_dn / m_adult - G * math.sin(th)
    put("dsn.brake_downhill_decel", round(a_dn, 2), "m/s2", "brake")
    put("dsn.brake_downhill_stop_m", round(vt * vt / (2 * a_dn), 1) if a_dn > 0 else 999, "m", "brake")

    # ---- the Delica ---------------------------------------------------------------------------
    put("dsn.delica_length_margin_mm", round((mm("delica.cargo_length_mm") - length) * 1000), "mm", "transport")
    put("dsn.delica_width_margin_mm", round((mm("delica.opening_width_max_mm") - width_t) * 1000), "mm", "transport")
    height = max(zw + 0.15, z_base + eh, N["hb_l"][2] + rail_od / 2)
    put("dsn.height_m", round(height, 3), "m", "layout")
    x_tail = x_id - d_id / 2 - tt
    length_w = wb + mm("ski.contact_length_mm") * 0.8 - min(x_tail, xb)
    put("dsn.winter_length_m", round(length_w, 3), "m", "winter")
    put("dsn.winter_height_m", round(height + lift, 3), "m", "winter")

    # ---- parts list ---------------------------------------------------------------------------
    bom = tdr.load_yaml((ROOT / "docs" / "data" / "bom.yaml").read_text(encoding="utf-8"))
    totals = {"parts": 0.0, "tools": 0.0}
    for line in bom["lines"]:
        if line["price"] not in v:
            raise SystemExit(f"bom.yaml: price key {line['price']} is not in the record")
        totals[line.get("group", "parts")] += v[line["price"]] * line["qty"]
    put("dsn.bom_parts_jpy", round(totals["parts"]), "JPY", "cost")
    put("dsn.bom_tools_jpy", round(totals["tools"]), "JPY", "cost")

    dims = {"length": length, "width": width, "width_transport": width_t, "height": height, "wheelbase": wb,
            "track_front": tf, "track_rear": tr, "track_rear_narrow": trn, "clearance": zr, "low_point": low,
            "axle_height": r, "x_front": xf, "x_back": xb}
    design = {
        "schema": 1,
        "axes": "x forward, y left, z up, metres; origin on the ground under the rear axle centre",
        "configs": CONFIGS,
        "lift": {"winter": round(lift, 4)},
        "future": ["water"],
        "dims": {k_: round(x, 4) for k_, x in dims.items()},
        "dims_winter": {"length": round(length_w, 4), "height": round(height + lift, 4), "x_front": round(wb + mm("ski.contact_length_mm") * 0.8, 4),
                        "x_back": round(min(x_tail, xb), 4), "belly": round(zp + lift, 4), "lift": round(lift, 4)},
        "riders": riders,
        "members": members,
        "items": items,
        "masses": [{"part": pt, "kg": round(m, 2), "pos": rnd(p_)} for pt, m, p_ in masses],
        "cg": {"x": round(cx, 4), "z": round(cz, 4), "mass": round(M, 2)},
        "delica": {"length": mm("delica.cargo_length_mm"), "width_max": mm("delica.cargo_width_max_mm"),
                   "width_min": mm("delica.cargo_width_min_mm"), "height": mm("delica.cargo_height_mm"),
                   "opening_min": mm("delica.opening_width_min_mm"), "opening_max": mm("delica.opening_width_max_mm"),
                   "lip": mm("delica.lip_height_mm")},
    }
    return out, design


def as_yaml(out):
    lines = [BEGIN]
    for key, val, unit, sec in out:
        lines += [f"  - key: {key}", f"    v: {val}"]
        if unit:
            lines.append(f"    unit: {unit}")
        lines += ["    status: calculated", "    basis:", f"      - docs/03-design.md#{sec}"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    out, design = build(values())
    text = json.dumps(design, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("ok" if ok else "docs/data/design.json is stale; run python calc/design.py --write")
        sys.exit(0 if ok else 1)
    for key, val, unit, _ in out:
        print(f"{key:32s} {val} {unit or ''}")
    if "--write" in sys.argv:
        p = ROOT / "record" / "values.yaml"
        t = p.read_text(encoding="utf-8")
        block = as_yaml(out)
        if BEGIN in t:
            head, rest = t.split(BEGIN + "\n", 1)
            t = head + block + rest.split(END + "\n", 1)[1]
        else:
            t = t.rstrip("\n") + "\n" + block
        p.write_text(t, encoding="utf-8", newline="\n")
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print("wrote record/values.yaml and docs/data/design.json")


if __name__ == "__main__":
    main()
