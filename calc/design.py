"""Design calculation of step 1.3: the straddle kart (D-030) - layout, frame, parts, mass, checks.

Reads every input from record/values.yaml (the design choices of docs/03-design.md, the
parts' catalogue data, and the assumptions of Q-017, Q-023, Q-033, Q-036, and Q-039), and writes:
- the calculated values back into record/values.yaml between its own markers, and
- docs/data/design.json, the geometry the navigator's drawings and 3D view draw.

The frame is solved as a space frame of tubes (calc/frame.py) and the geometry is searched
for interferences (calc/clash.py) in the summer and winter forms, at full steering lock and at
the ends of the rear suspension's travel.

    python calc/design.py          # print
    python calc/design.py --write  # also write the record and design.json
    python calc/design.py --check  # fail if design.json is not what would be written

Axes: x forward, y left, z up, in metres; origin on the ground under the rear axle centre.
"""
import importlib.util
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("tdr", ROOT / "tools" / "tdr.py")
tdr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tdr)
sys.path.insert(0, str(ROOT / "calc"))
import clash   # noqa: E402
import frame   # noqa: E402

OUT = ROOT / "docs" / "data" / "design.json"
BEGIN = "  # begin: generated by calc/design.py"
END = "  # end: generated by calc/design.py"
G = 9.81
CONFIGS = ["summer", "winter", "transport", "water"]
WHEELED = CONFIGS                          # the wheels stay on in winter (D-032)


def values():
    rec = tdr.Record(ROOT)
    return {it.d["key"]: it.d["v"] for it in rec.items["value"]}


def build(v):
    mm = lambda k: v[k] / 1000.0
    out = []          # calculated values: (key, value, unit, section)
    items = []        # drawn items
    members = []      # frame tubes, drawn
    N = {}            # frame and swing arm nodes
    tubes = []        # (node a, node b, od, t, part, on the swing arm)

    def put(key, val, unit, sec):
        out.append((key, val, unit, sec))

    def rf(x):                   # round every float, in lists too, so the file is the same everywhere
        if isinstance(x, float):
            return round(x, 4)
        if isinstance(x, (list, tuple)):
            return [rf(y) for y in x]
        return x

    def item(part, typ, configs=None, **kw):
        d = {"part": part, "type": typ, "configs": configs or CONFIGS}
        d.update({k: rf(x) for k, x in kw.items()})
        items.append(d)

    def rnd(p):
        return [round(c, 4) for c in p]

    def tube(a, b, od, t, part, arm=False, farm=None):
        tubes.append((a, b, od, t, part, arm or bool(farm)))
        m = {"part": part, "a": rnd(N[a]), "b": rnd(N[b]), "od": od, "t": t}
        if arm:
            m["arm"] = True
        if farm:
            m["front_arm"] = farm
        members.append(m)

    # ---- layout --------------------------------------------------------------------------
    wb = mm("lay.wheelbase_mm")
    tf, tr = mm("lay.track_front_mm"), mm("lay.track_rear_mm")
    # buggy-size tyres all year (D-032)
    tyre_d, tyre_wf, tyre_wr = mm("yr.tyre_dia_mm"), mm("yr.front_width_mm"), mm("yr.rear_width_mm")
    r = tyre_d / 2
    zr = mm("lay.rail_bottom_mm")
    rail_od, rail_t = mm("dsn.rail_od_mm"), mm("dsn.rail_t_mm")
    cross_od, cross_t = mm("dsn.cross_od_mm"), mm("dsn.cross_t_mm")
    zc = zr + rail_od / 2                      # rail centre line height
    ys, yk, yp = mm("lay.spine_half_width_mm"), mm("lay.kingpin_y_mm"), mm("lay.post_y_mm")
    xf, xb = wb + mm("lay.front_overhang_mm"), -mm("lay.rear_overhang_mm")
    fender = mm("lay.fender_margin_mm")
    width = max(tf + tyre_wf, tr + tyre_wr) + 2 * fender
    put("dsn.width_m", round(width, 3), "m", "layout")
    width_t = width                            # no narrowing for the car is needed
    put("dsn.width_transport_m", round(width_t, 3), "m", "transport")

    # ---- the engine unit lies low on the spine rails (D-037) -----------------------------------
    ul, uw, uh = mm("su.length_mm"), mm("su.width_mm"), mm("su.height_mm")
    yu, y2 = mm("lay.unit_y_mm"), mm("lay.chain420_y_mm")
    x_out = mm("lay.unit_out_x_mm")
    z_base = zr + rail_od + 0.011                      # unit on rubber mounts on its plate on the spine rails
    z_out = z_base + uh * 0.35                         # output shaft height in the unit (Q-023)
    xe = x_out - 0.05 + ul / 2
    z_seat_base = z_base + uh + 0.01
    zs = mm("lay.seat_height_mm")

    # ---- rear axle on a swing arm with one shock (D-036) --------------------------------------
    da = mm("dsn.axle_dia_mm")
    La = mm("lay.axle_length_mm")
    yb = mm("lay.bearing_y_mm")                       # the arm's sides and the two bearings
    h_b, l_b, h2_b = mm("brg.ucp207_h_mm"), mm("brg.ucp207_l_mm"), mm("brg.ucp207_h2_mm")
    arm_od, arm_t = rail_od, rail_t
    # the pivot sits just behind the unit, level with its output, so the chain keeps its length
    x_p, z_p = mm("lay.pivot_x_mm"), z_out
    z_bplate = r + h_b                               # bearings hang under plates on the arm's sides
    z_arm = z_bplate + 0.006 + arm_od / 2
    x_end = -l_b / 2 - 0.02
    x_brace = l_b / 2 + 0.005 + arm_od / 2          # the arm's brace just ahead of the bearing plates
    x_sl = mm("lay.shock_low_x_mm")

    def turn_xz(p, th):          # rotate a point about the pivot; positive lifts the axle behind it
        px, pz = p[0] - x_p, p[1] - z_p
        return (x_p + px * math.cos(th) + pz * math.sin(th), z_p - px * math.sin(th) + pz * math.cos(th))

    def axle_rise(th):
        return turn_xz((0.0, r), th)[1] - r

    def angle_for(rise):
        lo, hi = -0.6, 0.6
        for _ in range(60):
            mid = (lo + hi) / 2
            if axle_rise(mid) < rise:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2

    # The shock's lower eye sits on a lug over the arm's brace; the upper eye is placed so that,
    # laden, the shock is compressed by the sag, which the natural frequency alone sets. The struts
    # meet a cross tube on the shock's axis just beyond the upper eye, so its lug only pulls.
    sag = G / (2 * math.pi * v["sus.freq_hz"]) ** 2
    sl0 = (x_sl, z_arm + mm("lay.shock_low_rise_mm"))
    x_su = mm("lay.shock_top_x_mm")
    z_su = z_seat_base + 0.03

    def shock_len(th):
        return math.dist(turn_xz(sl0, th), (x_su, z_su))

    for _ in range(8):
        mr = (shock_len(0.0) - shock_len(angle_for(0.001))) / 0.001
        z_su = sl0[1] + math.sqrt(max((mm("shock.eye_mm") - mr * sag) ** 2 - (sl0[0] - x_su) ** 2, 0.0))
    ux, uz = x_su - sl0[0], z_su - sl0[1]
    x_c, z_c = x_su + 0.07 * ux / math.hypot(ux, uz), z_su + 0.07 * uz / math.hypot(ux, uz)   # the eye clear of the cross tube

    # ---- frame -----------------------------------------------------------------------------
    # Two spine rails under the engine unit from the pivot forward to the front beam; footboards
    # on three cross tubes either side; a front beam rising to the kingpins, with the bumper and
    # the stem's lower bearing on it; a tower to the stem's upper bearing. Behind the unit, posts
    # rise from the rails' ends through the pivot tube to two upper rails under the seat's rear,
    # and struts from the pivot tube to the shock's top close each side into a triangle. The
    # protective hoop (R-19, the part roll_bar) stands on the upper rails.
    zfoot = mm("lay.footrest_height_mm")
    xf0, xf1 = mm("lay.foot_x0_mm"), mm("lay.foot_x1_mm")
    yf0, yf1 = mm("lay.foot_y0_mm"), mm("lay.foot_y1_mm")
    xbar, zbar = mm("lay.bar_x_mm"), mm("lay.bar_z_mm")
    xh_, zt = mm("lay.hoop_x_mm"), mm("lay.rollbar_top_mm")
    z_u = z_seat_base - rail_od / 2 - 0.002            # upper rails under the seat's rear
    x_uf, x_uh, x_ub = 0.12, xh_ + 0.05, xb + 0.02
    z_fs = zfoot - 0.003 - cross_od / 2                # footboard cross tubes
    z_k = r - 0.045                                    # front beam ends under the kingpin bosses
    xm = (xf0 + xf1) / 2
    stations = [x_p, xf0, xm, xf1, 0.92, wb - 0.08]   # the rails stop short of the swing axles

    # steering: ATV knuckles on kingpins at ±yk; their arms point back at the rear axle's centre
    # (Ackermann) at the spindles' height, and the stem's pitman arm, as long as theirs, reaches
    # back to the tie rods' inner ends, so the tie rods lie across the kart and keep their length
    z_tie = r
    l_arm = 0.09
    beta = math.atan(yk / wb)
    x_tip, y_tip = wb - l_arm * math.cos(beta), yk - l_arm * math.sin(beta)
    wx, wz = x_tip - xbar, z_tie - zbar
    phi = math.asin(l_arm / math.hypot(wx, wz))
    ang = math.atan2(wz, wx) + phi                     # the stem axis passes ahead of the tie rods
    dx, dz = math.cos(ang), math.sin(ang)
    along = math.hypot(wx, wz) * math.cos(phi)
    x_q, z_q = xbar + along * dx, zbar + along * dz    # the stem's foot, at the pitman arm
    nx, nz = -dz, dx                                   # normal to the stem pointing back and down
    if nx > 0:
        nx, nz = -nx, -nz
    s_low = (xbar + 0.88 * (x_q - xbar), zbar + 0.88 * (z_q - zbar))   # flange bearings as drawn
    s_up = (xbar + 0.38 * (x_q - xbar), zbar + 0.38 * (z_q - zbar))
    put("dsn.stem_rake_deg", round(math.degrees(math.atan2(dx, -dz)), 1), "deg", "steering")

    # Front swing axles (D-039): each half of the front beam turns on a pivot near the centre line,
    # level with the tie rods' inner ends so that the wheels hardly steer as they rise, and one
    # shock per side runs from a lug on it to a cross tube over the front, placed as at the rear
    y_pv, z_pv = mm("lay.front_pivot_y_mm"), z_tie
    y_le, x_fs, y_te = mm("lay.front_shock_y_mm"), wb + mm("lay.front_shock_x_mm"), mm("lay.front_shock_top_y_mm")

    def turn_f(p, s, th):        # rotate (y, z) about a side's pivot; positive lifts the wheel
        dy, dz_ = (p[1] - s * y_pv) * s, p[2] - z_pv
        ny = dy * math.cos(th) - dz_ * math.sin(th)
        return (p[0], s * y_pv + s * ny, z_pv + dz_ * math.cos(th) + dy * math.sin(th))

    def angle_f(rise):
        lo, hi = -0.6, 0.6
        for _ in range(60):
            mid = (lo + hi) / 2
            if turn_f((wb, tf / 2, r), 1, mid)[2] - r < rise:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2

    z_fb = z_pv + (z_k - z_pv) * (y_le - y_pv) / (yk - y_pv)          # the half-beam's height at the lug
    fe0 = (x_fs, y_le, z_fb + 0.03)
    z_fte = fe0[2] + 0.2

    def fshock_len(th):
        return math.dist(turn_f(fe0, 1, th), (x_fs, y_te, z_fte))

    for _ in range(8):
        mr_f = (fshock_len(0.0) - fshock_len(angle_f(0.001))) / 0.001
        z_fte = fe0[2] + math.sqrt(max((mm("shock.eye_mm") - mr_f * sag) ** 2 - (y_le - y_te) ** 2, 0.0))
    uy, uz = y_te - y_le, z_fte - fe0[2]
    y_ft, z_ft = y_te + 0.10 * uy / math.hypot(uy, uz), z_fte + 0.10 * uz / math.hypot(uy, uz)   # the eye clear of the tower's tubes

    for i, x in enumerate(stations):
        for s, c in ((1, "l"), (-1, "r")):
            N[f"r{c}{i}"] = (x, s * ys, zc)
    for s, c in ((1, "l"), (-1, "r")):
        N[f"k{c}"] = (wb, s * yk, z_k)                  # on the swing axle, under the kingpin boss
        N[f"pv{c}"] = (wb, s * y_pv, z_pv)              # the front pivot on the frame
        N[f"fa{c}"] = (wb, s * y_pv, z_pv)              # the swing axle's end on it
        N[f"fb{c}"] = (wb, s * y_le, z_fb)
        N[f"fe{c}"] = (x_fs, s * y_le, fe0[2])          # the front shock's lower eye
        N[f"fte{c}"] = (x_fs, s * y_te, z_fte)          # and its upper eye
        N[f"ft{c}"] = (x_fs, s * y_ft, z_ft)            # the front cross tube, on the shock's axis
        N[f"fti{c}"] = (x_fs, s * 0.10, z_ft)           # where the tower's post from the pivot meets it, inboard of the shock
        N[f"rx{c}"] = (x_p, s * yp, zc)                 # where the rear post stands on the rails' rear cross tube
        N[f"sm{c}"] = (mm("lay.hpoint_x_mm"), s * 0.10, z_u)   # seat rails under the saddle, outside the air box
        N[f"sf{c}"] = (mm("lay.seat_x1_mm"), s * 0.10, z_u)
        N[f"b{c}"] = (xf - 0.02, s * ys, zc + 0.10)
        for j, x in enumerate((xf0 + 0.02, xm, xf1 - 0.02)):
            N[f"fs{c}{j}"] = (x, s * yf1, z_fs)
        N[f"fm{c}"] = (xm, s * (ys + yf1) / 2, z_fs)
        N[f"pe{c}"] = (x_p, s * (yb + 0.008), z_p)     # the pivot tube's ends, just past the sleeves
        N[f"ps{c}"] = (x_p, s * yb, z_p)               # where the arm's sleeve turns on it
        N[f"pf{c}"] = (x_p, s * yp, z_p)               # where the post crosses it
        N[f"uf{c}"] = (x_uf, s * yp, z_u)
        N[f"us{c}"] = (x_c, s * yp, z_c)                 # struts' tops, on the shock's axis
        N[f"um{c}"] = (x_c, s * yp, z_u)
        # the strut leaves the post above the arm's brace and crosses the upper rail at a joint
        f_ = 0.45
        N[f"pm{c}"] = (x_p + f_ * (x_uf - x_p), s * yp, z_p + f_ * (z_u - z_p))
        fx_ = (z_u - N[f"pm{c}"][2]) / (z_c - N[f"pm{c}"][2])
        N[f"ux{c}"] = (N[f"pm{c}"][0] + fx_ * (x_c - N[f"pm{c}"][0]), s * yp, z_u)
        N[f"uh{c}"] = (x_uh, s * yp, z_u)
        N[f"ub{c}"] = (x_ub, s * yp, z_u)
        N[f"hp{c}"] = (xh_, s * 0.20, zt - rail_od / 2)
    N["usc"] = (x_c, 0.0, z_c)
    # a keel on the centre line from the rails' front cross tube under the front pivots to the
    # bumper's middle, the only way past the swing axles and the tie rods' sweep
    N["rc5"] = (stations[-1], 0.0, zc)
    N["kc"] = (wb, 0.0, zc)
    N["bc"] = (xf - 0.02, 0.0, zc + 0.10)
    N["st0"] = (s_low[0] - 0.045 * nx, 0.0, s_low[1] - 0.045 * nz)   # the lower flange's plate ahead of the stem
    N["st1"] = (s_up[0] + 0.045 * nx, 0.0, s_up[1] + 0.045 * nz)
    last = len(stations) - 1
    for c in "lr":
        for i in range(last):
            tube(f"r{c}{i}", f"r{c}{i + 1}", rail_od, rail_t, "frame")
        tube(f"pv{c}", "kc", rail_od, rail_t, "frame")                 # the front pivot on the keel
        tube(f"fa{c}", f"fb{c}", rail_od, rail_t, "front_arms", farm=c)  # the swing axle
        tube(f"fb{c}", f"k{c}", rail_od, rail_t, "front_arms", farm=c)
        tube(f"fb{c}", f"fe{c}", rail_od, rail_t, "front_arms", farm=c)  # its lug for the shock
        tube(f"b{c}", "kc", rail_od, rail_t, "bumpers")                # the bumper braced to the keel
        tube(f"b{c}", f"ft{c}", rail_od, rail_t, "frame")              # the front tower on the bumper
        tube(f"pv{c}", f"fti{c}", rail_od, rail_t, "frame")            # and on the pivot, inboard of the shock
        tube(f"ft{c}", f"fte{c}", rail_od, rail_t, "frame")            # lug for the shock's top
        tube(f"uf{c}", f"sm{c}", rail_od, rail_t, "frame")           # seat rails
        tube(f"sm{c}", f"sf{c}", rail_od, rail_t, "frame")
        tube(f"sf{c}", f"r{c}4", rail_od, rail_t, "frame")
        tube(f"r{c}1", f"fs{c}0", cross_od, cross_t, "footrests")
        tube(f"r{c}2", f"fm{c}", cross_od, cross_t, "footrests")
        tube(f"fm{c}", f"fs{c}1", cross_od, cross_t, "footrests")
        tube(f"r{c}3", f"fs{c}2", cross_od, cross_t, "footrests")
        tube(f"fs{c}0", f"fs{c}1", cross_od, cross_t, "footrests")
        tube(f"fs{c}1", f"fs{c}2", cross_od, cross_t, "footrests")
        tube(f"rx{c}", f"pf{c}", rail_od, rail_t, "frame")             # post, lower part, upright clear of the arm
        tube(f"pf{c}", f"pm{c}", rail_od, rail_t, "frame")             # post, upper part
        tube(f"pm{c}", f"uf{c}", rail_od, rail_t, "frame")
        tube(f"pm{c}", f"ux{c}", rail_od, rail_t, "frame")             # strut to the shock's top
        tube(f"ux{c}", f"us{c}", rail_od, rail_t, "frame")
        tube(f"us{c}", f"um{c}", rail_od, rail_t, "frame")
        tube(f"uf{c}", f"ux{c}", cross_od, cross_t, "frame")
        tube(f"ux{c}", f"um{c}", cross_od, cross_t, "frame")
        tube(f"um{c}", f"uh{c}", cross_od, cross_t, "frame")
        tube(f"uh{c}", f"ub{c}", cross_od, cross_t, "frame")
        tube(f"pf{c}", f"ps{c}", rail_od, rail_t, "frame")             # the pivot tube
        tube(f"ps{c}", f"pe{c}", rail_od, rail_t, "frame")
        tube(f"us{c}", f"hp{c}", rail_od, rail_t, "roll_bar")          # the hoop stands on the struts' tops
        tube(f"hp{c}", f"ub{c}", cross_od, cross_t, "roll_bar")
        tube(f"r{c}4", "st1", cross_od, cross_t, "frame")              # tower to the upper bearing
        tube(f"fti{c}", "st0", cross_od, cross_t, "frame")             # the lower bearing from the tower, clear of the pitman arm
    tube("rl0", "rxl", rail_od, rail_t, "frame")                      # the rails' rear cross tube, carrying the posts
    tube("rxl", "rxr", rail_od, rail_t, "frame")
    tube("rxr", "rr0", rail_od, rail_t, "frame")
    keel_od, keel_t = mm("dsn.keel_od_mm"), mm("dsn.keel_t_mm")      # a larger tube where an offset impact bends it
    tube(f"rl{last}", "rc5", keel_od, keel_t, "frame")
    tube("rc5", f"rr{last}", keel_od, keel_t, "frame")
    tube("rc5", "kc", keel_od, keel_t, "frame")                       # the keel
    tube("kc", "bc", keel_od, keel_t, "bumpers")
    tube("bl", "bc", rail_od, rail_t, "bumpers")
    tube("bc", "br", rail_od, rail_t, "bumpers")
    tube("ftl", "ftil", rail_od, rail_t, "frame")
    tube("ftil", "ftir", rail_od, rail_t, "frame")
    tube("ftir", "ftr", rail_od, rail_t, "frame")
    tube("pfl", "pfr", rail_od, rail_t, "frame")
    tube("ufl", "ufr", cross_od, cross_t, "frame")
    tube("usl", "usc", rail_od, rail_t, "frame")
    tube("usc", "usr", rail_od, rail_t, "frame")
    tube("ubl", "ubr", cross_od, cross_t, "frame")
    tube("hpl", "hpr", rail_od, rail_t, "roll_bar")

    # the swing arm: two sides from the sleeves on the pivot tube, bent level ahead of the bearing
    # plates and on past the axle, a brace at the bend with a lug for the shock's lower eye, and a
    # cross tube behind the axle
    for s, c in ((1, "l"), (-1, "r")):
        N[f"as{c}"] = (x_p, s * yb, z_p)
        N[f"ab{c}"] = (x_brace, s * yb, z_arm)
        N[f"ax{c}"] = (0.0, s * yb, z_arm)
        N[f"ae{c}"] = (x_end, s * yb, z_arm)
        tube(f"as{c}", f"ab{c}", arm_od, arm_t, "swing_arm", arm=True)
        tube(f"ab{c}", f"ax{c}", arm_od, arm_t, "swing_arm", arm=True)
        tube(f"ax{c}", f"ae{c}", arm_od, arm_t, "swing_arm", arm=True)
    N["abc"] = (x_brace, 0.0, z_arm)
    tube("abl", "abc", arm_od, arm_t, "swing_arm", arm=True)
    tube("abc", "abr", arm_od, arm_t, "swing_arm", arm=True)
    tube("ael", "aer", rail_od, rail_t, "swing_arm", arm=True)
    for c in "lr":
        item("swing_arm", "cyl", pos=list(N[f"ps{c}"]), axis="y", d=0.042, l=0.03, arm=True)   # sleeves

    rho = v["dsn.steel_density_kg_m3"]
    tube_mass = lambda od_, t_, L: rho * math.pi * (od_ * od_ - (od_ - 2 * t_) ** 2) / 4 * L
    lens = {}
    for a, b, od_, t_, part, _ in tubes:
        key = ("arm" if part == "swing_arm" else "roll" if part == "roll_bar" else "main" if od_ == rail_od else "cross")
        lens[key] = lens.get(key, 0.0) + math.dist(N[a], N[b])
    put("dsn.tube_main_m", round(lens["main"], 2), "m", "frame")
    put("dsn.tube_cross_m", round(lens["cross"], 2), "m", "frame")
    put("dsn.tube_roll_m", round(lens["roll"], 2), "m", "rollbar")
    put("dsn.tube_arm_m", round(lens["arm"], 2), "m", "suspension")
    m_frame = sum(tube_mass(od_, t_, math.dist(N[a], N[b])) for a, b, od_, t_, part, _ in tubes
                  if part in ("frame", "bumpers", "footrests"))
    m_roll = sum(tube_mass(od_, t_, math.dist(N[a], N[b])) for a, b, od_, t_, part, _ in tubes if part == "roll_bar")
    m_arm = sum(tube_mass(od_, t_, math.dist(N[a], N[b])) for a, b, od_, t_, part, _ in tubes if part == "swing_arm")
    # footboards on the cross tubes either side of the unit, each with a toe board at its front
    m_foot = 0.0
    for s in (1, -1):
        item("footrests", "plate", pos=[xm, s * (yf0 + yf1) / 2, zfoot - 0.0015], size=[xf1 - xf0, yf1 - yf0, 0.003])
