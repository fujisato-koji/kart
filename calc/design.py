"""Design calculation of step 1.3: the straddle kart (D-030) - layout, frame, parts, mass, checks.

Reads every input from record/values.yaml (the design choices of docs/03-design.md, the
parts' catalogue data, and the assumptions of Q-017, Q-023, Q-033, and Q-036), and writes:
- the calculated values back into record/values.yaml between its own markers, and
- docs/data/design.json, the geometry the navigator's drawings and 3D view draw.

    python calc/design.py          # print
    python calc/design.py --write  # also write the record and design.json
    python calc/design.py --check  # fail if design.json is not what would be written

Axes: x forward, y left, z up, in metres; origin on the ground under the rear axle centre.
"""
import importlib.util
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("tdr", ROOT / "tools" / "tdr.py")
tdr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tdr)

OUT = ROOT / "docs" / "data" / "design.json"
BEGIN = "  # begin: generated by calc/design.py"
END = "  # end: generated by calc/design.py"
G = 9.81
CONFIGS = ["summer", "winter", "transport", "water"]
WHEELED = CONFIGS                          # the wheels stay on in winter (D-032)


def values():
    rec = tdr.Record(ROOT)
    return {it.d["key"]: it.d["v"] for it in rec.items["value"]}


def build(v):
    mm = lambda k: v[k] / 1000.0
    out = []          # calculated values: (key, value, unit, section)
    items = []        # drawn items
    members = []      # frame tubes

    def put(key, val, unit, sec):
        out.append((key, val, unit, sec))

    def item(part, typ, configs=None, **kw):
        d = {"part": part, "type": typ, "configs": configs or CONFIGS}
        d.update({k: (round(x, 4) if isinstance(x, float) else x) for k, x in kw.items()})
        items.append(d)

    def rnd(p):
        return [round(c, 4) for c in p]

    # ---- layout --------------------------------------------------------------------------
    wb = mm("lay.wheelbase_mm")
    tf, tr = mm("lay.track_front_mm"), mm("lay.track_rear_mm")
    # buggy-size tyres all year (D-032)
    tyre_d, tyre_wf, tyre_wr = mm("yr.tyre_dia_mm"), mm("yr.front_width_mm"), mm("yr.rear_width_mm")
    r = tyre_d / 2
    zr = mm("lay.rail_bottom_mm")
    rail_od, rail_t = mm("dsn.rail_od_mm"), mm("dsn.rail_t_mm")
    cross_od, cross_t = mm("dsn.cross_od_mm"), mm("dsn.cross_t_mm")
    zc = zr + rail_od / 2                      # rail centre line height
    ys, yk = mm("lay.spine_half_width_mm"), mm("lay.kingpin_y_mm")
    xf, xb = wb + mm("lay.front_overhang_mm"), -mm("lay.rear_overhang_mm")
    fender = mm("lay.fender_margin_mm")
    length = xf - xb
    width = max(tf + tyre_wf, tr + tyre_wr) + 2 * fender
    put("dsn.width_m", round(width, 3), "m", "layout")
    width_t = width                            # no narrowing for the car is needed
    put("dsn.width_transport_m", round(width_t, 3), "m", "transport")

    # ---- rear axle position and bearings (sizes needed by the frame) ---------------------------
    da = mm("dsn.axle_dia_mm")
    La = mm("lay.axle_length_mm")
    yb, ybm = mm("lay.bearing_y_mm"), mm("lay.bearing_mid_y_mm")
    h205, l205, h2_205 = mm("brg.ucp205_h_mm"), mm("brg.ucp205_l_mm"), mm("brg.ucp205_h2_mm")
    # The bearings hang upside down under plates on outriggers; the spine rises over the axle
    z_bplate = r + h205
    zc_hi = z_bplate + 0.006 + rail_od / 2
    put("dsn.axle_rail_gap_mm", round((zc_hi - rail_od / 2 - (r + da / 2)) * 1000), "mm", "frame")
    xk = mm("lay.kick_x_mm")

    # ---- frame -----------------------------------------------------------------------------
    # A spine of two rails under the engine unit, rising behind x = kick over the rear axle,
    # outriggers to the axle bearings, a front beam to the kingpins, a bumper, footrest
    # supports, a tower for the steering stem's upper bearing, and a protective hoop behind
    # the seat (R-19, the part roll_bar).
    zfoot = mm("lay.footrest_height_mm")
    xf0, xf1 = mm("lay.foot_x0_mm"), mm("lay.foot_x1_mm")
    yf0, yf1 = mm("lay.foot_y0_mm"), mm("lay.foot_y1_mm")
    xbar, zbar = mm("lay.bar_x_mm"), mm("lay.bar_z_mm")
    x_pit, z_pit = wb - 0.06, zc + 0.06        # the stem's lower end and its drop arm
    # the stem's upper bearing, a third of the way down from the bar
    x_sb, z_sb = xbar + (x_pit - xbar) * 0.35, zbar + (z_pit - zbar) * 0.35
    xh_, zt = mm("lay.hoop_x_mm"), mm("lay.rollbar_top_mm")
    N = {
        "rl0": (xb + 0.03, ys, zc_hi), "rr0": (xb + 0.03, -ys, zc_hi),
        "rlk": (0.08, ys, zc_hi), "rrk": (0.08, -ys, zc_hi),
        "rl1": (xk, ys, zc), "rr1": (xk, -ys, zc),
        "rl2": (0.55, ys, zc), "rr2": (0.55, -ys, zc),
        "rl3": (0.85, ys, zc), "rr3": (0.85, -ys, zc),
        "fl": (wb, ys, zc + 0.02), "fr": (wb, -ys, zc + 0.02),
        "kl": (wb, yk, zc + 0.02), "kr": (wb, -yk, zc + 0.02),
        "bl": (xf - 0.02, ys, zc + 0.10), "br": (xf - 0.02, -ys, zc + 0.10),
        "ol0": (-0.11, ys, zc_hi), "ol1": (-0.11, yb + 0.02, zc_hi), "ol2": (0.11, yb + 0.02, zc_hi), "ol3": (0.11, ys, zc_hi),
        "or0": (-0.11, -ys, zc_hi), "or1": (-0.11, -yb - 0.02, zc_hi), "or2": (0.11, -yb - 0.02, zc_hi), "or3": (0.11, -ys, zc_hi),
        "fsl0": (xf0 + 0.02, ys, zc), "fsl1": (xf0 + 0.02, yf1, zfoot - 0.003 - cross_od / 2),
        "fsl2": (xf1 - 0.02, ys, zc), "fsl3": (xf1 - 0.02, yf1, zfoot - 0.003 - cross_od / 2),
        "fsr0": (xf0 + 0.02, -ys, zc), "fsr1": (xf0 + 0.02, -yf1, zfoot - 0.003 - cross_od / 2),
        "fsr2": (xf1 - 0.02, -ys, zc), "fsr3": (xf1 - 0.02, -yf1, zfoot - 0.003 - cross_od / 2),
        "st1": (x_sb, 0.0, z_sb - 0.03),
        "hp_lb": (-0.11, 0.25, zc_hi), "hp_rb": (-0.11, -0.25, zc_hi),
        "hp_l": (xh_, 0.22, zt - rail_od / 2), "hp_r": (xh_, -0.22, zt - rail_od / 2),
    }
    main = [("rl0", "rlk"), ("rlk", "rl1"), ("rl1", "rl2"), ("rl2", "rl3"), ("rl3", "fl"), ("fl", "bl"),
            ("rr0", "rrk"), ("rrk", "rr1"), ("rr1", "rr2"), ("rr2", "rr3"), ("rr3", "fr"), ("fr", "br")]
    cross = [("rl0", "rr0"), ("rl1", "rr1"), ("rl2", "rr2"), ("rl3", "rr3"), ("fl", "fr"), ("bl", "br"),
             ("fl", "kl"), ("fr", "kr"), ("rl3", "kl"), ("rr3", "kr"),
             ("ol0", "ol1"), ("ol1", "ol2"), ("ol2", "ol3"), ("or0", "or1"), ("or1", "or2"), ("or2", "or3"),
             ("fsl0", "fsl1"), ("fsl2", "fsl3"), ("fsl1", "fsl3"), ("fsr0", "fsr1"), ("fsr2", "fsr3"), ("fsr1", "fsr3"),
             ("rl3", "st1"), ("rr3", "st1"),
             ("hp_lb", "hp_l"), ("hp_l", "hp_r"), ("hp_r", "hp_rb"), ("hp_l", "rl0"), ("hp_r", "rr0")]
    tube_len = {"main": 0.0, "cross": 0.0, "roll": 0.0}
    for a, b in main:
        members.append({"part": "frame", "a": rnd(N[a]), "b": rnd(N[b]), "od": rail_od, "t": rail_t})
        tube_len["main"] += math.dist(N[a], N[b])
    for a, b in cross:
        part = "bumpers" if a == "bl" else "frame"
        if a.startswith("hp") or b.startswith("hp"):
            part = "roll_bar"
        if a.startswith("fs") or b.startswith("fs"):
            part = "footrests"
        od_, t_ = (rail_od, rail_t) if part == "roll_bar" else (cross_od, cross_t)
        members.append({"part": part, "a": rnd(N[a]), "b": rnd(N[b]), "od": od_, "t": t_})
        tube_len["roll" if part == "roll_bar" else "cross"] += math.dist(N[a], N[b])
    put("dsn.tube_main_m", round(tube_len["main"], 2), "m", "frame")
    put("dsn.tube_cross_m", round(tube_len["cross"], 2), "m", "frame")
    put("dsn.tube_roll_m", round(tube_len["roll"], 2), "m", "rollbar")
    rho = v["dsn.steel_density_kg_m3"]
    tube_mass = lambda od_, t_, L: rho * math.pi * (od_ * od_ - (od_ - 2 * t_) ** 2) / 4 * L
    m_frame = tube_mass(rail_od, rail_t, tube_len["main"]) + tube_mass(cross_od, cross_t, tube_len["cross"])
    # footboards on the supports, either side of the engine unit
    m_foot = 0.0
    for s in (1, -1):
        item("footrests", "plate", pos=[(xf0 + xf1) / 2, s * (yf0 + yf1) / 2, zfoot - 0.0015], size=[xf1 - xf0, yf1 - yf0, 0.003])
        m_foot += rho * (xf1 - xf0) * (yf1 - yf0) * 0.003

    # ---- masses and centre of mass ---------------------------------------------------------
    masses = []   # (part, kg, (x, y, z))

    def mass(part, kg, pos):
        masses.append((part, kg, pos))

    mass("frame", m_frame, (0.45, 0.0, zc + 0.03))
    m_roll = tube_mass(rail_od, rail_t, tube_len["roll"])
    mass("roll_bar", m_roll, (xh_ + 0.05, 0.0, (zc_hi + zt) / 2))
    mass("footrests", m_foot, ((xf0 + xf1) / 2, 0.0, zfoot))

    # ---- rear axle, hubs, wheels, bearings, brake --------------------------------------------
    item("axle_shaft", "cyl", pos=[0.0, 0.0, r], axis="y", d=da, l=La)
    mass("axle_shaft", rho * math.pi * da * da / 4 * La, (0.0, 0.0, r))
    plates = 0.0
    for yy in (yb, ybm, -yb):
        item("axle_bearings", "pillow", pos=[0.0, yy, z_bplate], h=h205, l=l205, h2=h2_205, bore=da, axis="y", inverted=True)
        mass("axle_bearings", v["brg.ucp205_mass_kg"], (0.0, yy, r))
        item("frame", "plate", pos=[0.0, yy, z_bplate + 0.003], size=[0.24, 0.07, 0.006])
        plates += rho * 0.24 * 0.07 * 0.006
    low_bearing = r - (h2_205 - h205)
    for cfg in WHEELED:
        for s in (1, -1):
            item("rear_hubs", "hub", configs=[cfg], pos=[0.0, s * (tr / 2 - 0.02), r], axis="y", d=0.07, l=0.05)
            item("rear_wheels", "wheel", configs=[cfg], pos=[0.0, s * tr / 2, r], axis="y", od=tyre_d, width=tyre_wr, rim=0.203)
    put("dsn.hub_bearing_gap_mm", round((tr / 2 - 0.02 - 0.025 - (yb + 0.0171)) * 1000), "mm", "axle")
    for s in (1, -1):
        mass("rear_wheels", v["yr.wheel_mass_kg"], (0.0, s * tr / 2, r))
        mass("rear_hubs", 0.8, (0.0, s * (tr / 2 - 0.02), r))
    dd = mm("lay.disc_dia_mm")
    yd = mm("lay.brake_y_mm")
    item("brake", "disc", pos=[0.0, yd, r], axis="y", d=dd, t=0.004)
    item("brake", "caliper", pos=[0.0, yd, r + dd / 2 - 0.02], size=[0.06, 0.04, 0.05])
    mass("brake", v["dsn.brake_mass_kg"], (0.0, yd, r))
    low_disc = r - dd / 2

    # ---- powertrain: a 50 cc scooter's engine unit under the seat, one 420 chain ---------------
    # The unit lies along the kart's centre under the seat, as in the scooter, cylinder forward,
    # its output at the rear end on the left; a short 420 chain runs to the axle sprocket
    # beside the middle bearing. Slotted holes under the unit's plate tension the chain.
    p420 = 0.0127
    t_out, t4 = v["gear.t_out420"], v["gear.t_axle420"]
    pd_out = p420 / math.sin(math.pi / t_out)
    pd_ax = p420 / math.sin(math.pi / t4)
    chain_r = t4 / t_out
    ratio_top = v["eng50.cvt_high"] * v["su.final_ratio"] * chain_r
    ratio = v["eng50.cvt_low"] * v["su.final_ratio"] * chain_r   # lowest overall ratio, for climbing and the chain pull
    put("dsn.ratio_top", round(ratio_top, 2), None, "drive")
    put("dsn.ratio", round(ratio, 2), None, "drive")
    v_top = v["su.rev_limit_rpm"] / ratio_top / 60 * math.pi * tyre_d * 3.6
    put("dsn.top_speed_kmh", round(v_top, 2), "km/h", "drive")
    ul, uw, uh = mm("su.length_mm"), mm("su.width_mm"), mm("su.height_mm")
    yu, y2 = mm("lay.unit_y_mm"), mm("lay.chain420_y_mm")
    x_out = mm("lay.unit_out_x_mm")
    z_base = zr + rail_od + 0.006                      # unit plate on the spine rails
    z_out = z_base + uh * 0.35                         # output shaft height in the unit (Q-023)
    xe = x_out - 0.05 + ul / 2
    item("frame", "plate", pos=[xe, yu, z_base - 0.003], size=[ul * 0.8, 2 * ys - 0.02, 0.006])
    plates += rho * ul * 0.8 * (2 * ys - 0.02) * 0.006
    item("engine", "scooter_unit", pos=[xe, yu, z_base], length=ul, width=uw, height=uh, out=[x_out, y2 + 0.025, z_out],
         cylinder="+x")
    mass("engine", v["su.mass_kg"], (xe, yu, z_base + uh * 0.45))
    mass("fuel", v["dsn.fuel_mass_kg"], (xe + ul * 0.35, yu, z_base + uh * 0.9))
    mass("frame", plates, (0.2, 0.0, zc))
    item("chain_final", "sprocket", configs=WHEELED, pos=[x_out, y2, z_out], axis="y", teeth=t_out, pd=pd_out, od=pd_out + 0.6 * p420,
         t=0.006)
    od_ax = pd_ax + 0.6 * p420
    item("chain_final", "sprocket", configs=WHEELED, pos=[0.0, y2, r], axis="y", teeth=t4, pd=pd_ax, od=od_ax, t=0.006)
    c420 = math.dist((x_out, z_out), (0.0, r))

    def links(c, t1, t2):
        exact = 2 * c / p420 + (t1 + t2) / 2 + p420 * (t2 - t1) ** 2 / (4 * math.pi ** 2 * c)
        return math.ceil(exact / 2) * 2

    put("dsn.chain420_centre_mm", round(c420 * 1000), "mm", "drive")
    put("dsn.chain420_links", links(c420, t_out, t4), None, "drive")
    put("dsn.unit_front_x_mm", round((xe + ul / 2) * 1000), "mm", "drive")
    item("chain_final", "chain", configs=WHEELED, pos=[x_out, y2, z_out], to=[0.0, y2, r], r1=pd_out / 2, r2=pd_ax / 2, axis="y")
    mass("chain_final", 0.8, (x_out / 2, y2, (z_out + r) / 2))
    low_spr = r - od_ax / 2
    xg0, xg1 = 0.14, x_out + 0.07
    item("guards", "guard", pos=[(xg0 + xg1) / 2, y2 + 0.035, (z_out + r) / 2 + 0.02], size=[xg1 - xg0, 0.004, 0.17])
    mass("guards", 0.6, ((xg0 + xg1) / 2, y2 + 0.035, r + 0.05))
    low = min(low_bearing, low_disc, low_spr, zr)
    put("dsn.low_point_mm", round(low * 1000), "mm", "axle")

    # ---- front: spindles, wheels -----------------------------------------------------------
    for s in (1, -1):
        king = (wb, s * yk, zc + 0.02)
        item("spindles", "spindle", pos=rnd(king), side=s, to=[wb, s * tf / 2, r], arm=0.09)
        mass("spindles", 1.2, (wb, s * (yk + tf / 2) / 2, r))
        for cfg in WHEELED:
            item("front_wheels", "wheel", configs=[cfg], pos=[wb, s * tf / 2, r], axis="y", od=tyre_d, width=tyre_wf, rim=0.203)
        mass("front_wheels", v["yr.wheel_mass_kg"], (wb, s * tf / 2, r))
        # the second brake system: small discs on the front hubs from the left lever (R-21)
        item("hand_brake", "disc", configs=WHEELED, pos=[wb, s * (tf / 2 - 0.07), r], axis="y", d=mm("lay.front_disc_dia_mm"), t=0.003)
        item("hand_brake", "caliper", configs=WHEELED, pos=[wb - mm("lay.front_disc_dia_mm") / 2 + 0.015, s * (tf / 2 - 0.07), r],
             size=[0.04, 0.035, 0.05])
        mass("front_hubs", 0.8, (wb, s * (tf / 2 - 0.02), r))
        mass("hand_brake", 0.5, (wb, s * (tf / 2 - 0.07), r))
        # fenders over all four tyres (R-30)
        for xw in (0.0, wb):
            item("fenders", "fender", configs=WHEELED, pos=[xw, s * tf / 2 if xw else s * tr / 2, r], od=tyre_d + 2 * fender,
                 width=(tyre_wf if xw else tyre_wr) + 2 * fender)
    mass("fenders", v["dsn.fender_mass_kg"], (wb / 2, 0.0, r + 0.1))

    # ---- steering: the donor's handlebar on a raked stem ---------------------------------------
    wbar = mm("lay.bar_width_mm")
    item("handlebar", "rod", pos=[xbar, 0.0, zbar], to=[x_pit, 0.0, z_pit], d=0.025)
    item("handlebar", "handlebar", pos=[xbar, 0.0, zbar], width=wbar, d=0.022, grips=0.12)
    for s in (1, -1):
        item("tie_rods", "rod", pos=[x_pit, 0.0, z_pit - 0.02], to=[wb - 0.09, s * (yk - 0.02), zc + 0.03], d=0.010)
    mass("handlebar", v["dsn.steering_mass_kg"], ((xbar + x_pit) / 2, 0.0, (zbar + z_pit) / 2))
    steer = math.radians(v["lay.steer_max_deg"])
    turn = wb / math.tan(steer) + tf / 2
    put("dsn.turn_radius_m", round(turn, 2), "m", "steering")

    # ---- seat, footrests, riders -------------------------------------------------------------
    zs = mm("lay.seat_height_mm")
    sx0, sx1, sw = mm("lay.seat_x0_mm"), mm("lay.seat_x1_mm"), mm("lay.seat_width_mm")
    z_seat_base = z_base + uh + 0.01
    item("seat", "saddle", pos=[(sx0 + sx1) / 2, 0.0, z_seat_base], l=sx1 - sx0, w=sw, h=zs - z_seat_base)
    mass("seat", v["dsn.seat_mass_kg"], ((sx0 + sx1) / 2, 0.0, (z_seat_base + zs) / 2))
    mass("misc", v["dsn.misc_mass_kg"], (0.4, 0.0, zc + 0.1))
    raise_c = mm("lay.child_foot_raise_mm")
    # a raised step bolts on each footboard for a child (D-030)
    for s in (1, -1):
        item("footrests", "plate", configs=CONFIGS, rider="child", pos=[(xf0 + xf1) / 2 + 0.05, s * (yf0 + yf1) / 2, zfoot + raise_c / 2],
             size=[(xf1 - xf0) * 0.6, yf1 - yf0, raise_c])
    mass_steps = rho * (xf1 - xf0) * 0.6 * (yf1 - yf0) * 0.003 * 2 * 2   # two steps of two plates each
    riders = {}
    for who, stat, mkey, cgk, xh, zfoot_r in (
            ("adult", v["rider.stature_max_cm"] / 100, v["rider.mass_max_kg"], v["rider.cg_above_seat_m"],
             mm("lay.hpoint_x_mm"), zfoot),
            ("child", v["rider.stature_min_cm"] / 100, v["rider.mass_child_kg"], v["rider.cg_above_seat_child_m"],
             mm("lay.child_hip_x_mm"), zfoot + raise_c)):
        hip = (xh, 0.0, zs + 0.03)
        heel_x = min(max(xh + 0.12 * stat / 1.7, xf0 + 0.04), xf1 - 0.04)
        foot_y = (yf0 + yf1) / 2
        hand = (xbar - 0.02, wbar / 2 - 0.06, zbar)
        riders[who] = {"stature": stat, "mass": mkey, "hip": rnd(hip), "heel": rnd((heel_x, foot_y, zfoot_r + 0.02)),
                       "stance": "straddle", "foot_y": round(foot_y, 4), "hand": rnd(hand), "cg_above_seat": cgk}
    # a child fits if, standing on the footrests, the crotch clears the seat by rider.child_fit_clear_mm (P69)
    crotch = v["rider.child_crotch_ratio"] * v["rider.stature_min_cm"] / 100
    put("dsn.child_fit_margin_mm", round((crotch - (zs - zfoot - raise_c) - mm("rider.child_fit_clear_mm")) * 1000), "mm", "fit")

    # ---- road equipment (R-20, R-21, R-23) -----------------------------------------------------
    xbk = xb + 0.03
    item("lighting", "lamp", pos=[xbar + 0.10, 0.0, zbar - 0.06], role="head", color="white", facing="+x", d=0.11)
    for s in (1, -1):
        item("lighting", "lamp", pos=[xf - 0.02, s * 0.30, zc + 0.14], role="turn", color="amber", facing="+x", d=0.05)
        item("lighting", "lamp", pos=[xh_ - 0.02, s * 0.25, zc_hi + 0.30], role="turn", color="amber", facing="-x", d=0.05)
        item("mirrors", "mirror", pos=[xbar - 0.04, s * (wbar / 2 - 0.02), zbar + 0.16],
             stem=[xbar - 0.02, s * (wbar / 2 - 0.16), zbar + 0.02], d=0.10, facing="-x")
    item("lighting", "lamp", pos=[xbk - 0.02, 0.0, zc_hi + 0.10], role="tail_stop", color="red", facing="-x", size=[0.02, 0.12, 0.05])
    item("lighting", "lamp", pos=[xbk - 0.035, 0.0, zc_hi + 0.02], role="reflector", color="red", facing="-x", size=[0.01, 0.06, 0.03])
    item("number_plate", "plate_number", pos=[xbk - 0.03, -0.17, zc_hi + 0.04], size=[0.004, 0.17, 0.10])
    item("lighting", "lamp", pos=[xbk - 0.01, -0.17, zc_hi + 0.11], role="plate", color="white", facing="-z", d=0.03)
    item("horn", "box", pos=[wb + 0.12, 0.0, zc + 0.02], size=[0.06, 0.08, 0.06])
    item("speedometer", "gauge", pos=[xbar + 0.02, 0.0, zbar + 0.07], d=0.08, facing="-x")
    item("battery", "box", pos=[0.05, -0.08, zr + rail_od + 0.06], size=[0.11, 0.07, 0.09])
    mass("battery", v["dsn.battery_mass_kg"], (0.05, -0.08, zr + rail_od + 0.06))
    item("hand_brake", "lever", pos=[xbar, wbar / 2 - 0.08, zbar], to=[xbar + 0.08, wbar / 2 - 0.10, zbar - 0.01])
    mass("road", v["dsn.road_kit_mass_kg"], (0.3, 0.0, zc + 0.3))

    # ---- sled pan (D-023, D-028): UHMW polyethylene under the spine, kept in both forms --------
    zp = mm("hull.bottom_clear_mm")
    tb = mm("hull.bottom_t_mm")
    x0, x1 = mm("lay.pan_x0_mm"), mm("lay.pan_x1_mm")
    yo = mm("lay.pan_half_beam_mm")
    xbw, zbw, ybw = mm("lay.bow_x_mm"), zp + mm("lay.bow_rise_mm"), mm("lay.bow_half_beam_mm")
    item("sled_pan", "plate", pos=[(x0 + x1) / 2, 0.0, zp + tb / 2], size=[x1 - x0, 2 * yo, tb])
    sheet_a = (x1 - x0) * 2 * yo * tb
    st = [(x1 + fx * (xbw - x1), yo + fy * (ybw - yo), zp + fz * (zbw - zp))
          for fx, fy, fz in ((0, 0, 0), (0.35, 0.3, 0.1), (0.7, 0.65, 0.4), (1, 1, 1))]
    for (xa, ya, za), (xb_, yb_, zb_) in zip(st, st[1:]):
        item("sled_pan", "sheet", corners=[[xa, ya, za], [xb_, yb_, zb_], [xb_, -yb_, zb_], [xa, -ya, za]], t=tb)
        sheet_a += math.dist((xa, za), (xb_, zb_)) * (ya + yb_) * tb
    m_pan = sheet_a * v["hull.sheet_density_kg_m3"]
    mass("sled_pan", m_pan, ((x0 + xbw) / 2, 0.0, zp + 0.02))
    put("dsn.pan_mass_kg", round(m_pan, 1), "kg", "winter")

    # ---- winter form W6 (D-032): skis beside the front wheels, chains on the rear tyres ---------
    # Height-adjustable skis bolt to the steering knuckles inside the front tyres and steer with
    # them; they are drawn with their soles level with the tyres'. Chains go on the rear tyres.
    lift = 0.0
    W = ["winter"]
    y_ski = tf / 2 - tyre_wf / 2 - mm("lay.ski_gap_mm") - mm("ski.width_mm") / 2
    put("dsn.ski_y_mm", round(y_ski * 1000), "mm", "winter")
    for s in (1, -1):
        item("skis", "ski", configs=W, ground=True, pos=[wb, s * y_ski, 0.0], l=mm("ski.contact_length_mm") * 1.6,
             w=mm("ski.width_mm"), stub_z=r)
        item("snow_chains", "chains", configs=W, pos=[0.0, s * tr / 2, r], axis="y", od=tyre_d, width=tyre_wr)

    # ---- future water version (D-027): not required, shown only ----------------------------
    yfl = width / 2 + 0.04 + mm("lay.float_dia_mm") / 2
    for s in (1, -1):
        item("side_floats", "float", configs=["water"], future=True, pos=[(xb + xf) / 2, s * yfl, zp + mm("lay.float_dia_mm") / 2],
             l=xf - xb, d=mm("lay.float_dia_mm"))
        item("side_floats", "rod", configs=["water"], future=True, pos=[0.45, s * ys, zc], to=[0.45, s * yfl, zp + 0.15], d=0.025)
    item("outboard", "outboard", configs=["water"], future=True, pos=[xb - 0.06, 0.0, zc_hi + 0.10], shaft=0.60, tilt_deg=60)
    item("outboard", "box", configs=["water"], future=True, pos=[xb + 0.10, 0.20, zc_hi + 0.10], size=[0.25, 0.17, 0.22])

    # ---- totals: mass and centre of mass ----------------------------------------------------
    M = sum(m for _, m, _ in masses)
    cx = sum(m * p_[0] for _, m, p_ in masses) / M
    cy = sum(m * p_[1] for _, m, p_ in masses) / M
    cz = sum(m * p_[2] for _, m, p_ in masses) / M
    put("dsn.mass_kg", round(M, 1), "kg", "mass")
    put("dsn.cg_x_m", round(cx, 3), "m", "mass")
    put("dsn.cg_y_m", round(cy, 3), "m", "mass")
    put("dsn.cg_z_m", round(cz, 3), "m", "mass")
    put("dsn.frame_mass_kg", round(m_frame, 1), "kg", "frame")

    def rider_cg(rd, dz=0.0):
        return rd["hip"][0] + 0.05, rd["hip"][1], rd["hip"][2] + rd["cg_above_seat"] - 0.03 + dz

    def half_track(cx_, cy_, t_front, t_rear):
        return t_rear / 2 + (t_front / 2 - t_rear / 2) * (cx_ / wb) - abs(cy_)

    for who in ("adult", "child"):
        rd = riders[who]
        mt = M + rd["mass"] + (mass_steps if who == "child" else 0.0)
        x_r, y_r, z_r = rider_cg(rd)
        cxt = (M * cx + rd["mass"] * x_r) / mt
        cyt = (M * cy + rd["mass"] * y_r) / mt
        czt = (M * cz + rd["mass"] * z_r) / mt
        rear = 1 - cxt / wb
        put(f"dsn.rear_share_{who}", round(rear, 3), None, "mass")
        put(f"dsn.cg_side_{who}_mm", round(cyt * 1000), "mm", "mass")
        put(f"dsn.cg_height_{who}_m", round(czt, 3), "m", "mass")
        put(f"dsn.tip_ratio_{who}", round(half_track(cxt, cyt, tf, tr) / czt, 2), None, "stability")
        put(f"dsn.pitch_ratio_{who}", round(min(cxt, wb - cxt) / czt, 2), None, "stability")
        if who == "adult":
            m_adult, rear_adult, x_adult, h_adult = mt, rear, x_r, czt

    # winter totals: the summer kart with its skis and chains on
    mw = list(masses)
    for s in (1, -1):
        mw.append(("skis", v["ski.pair_kg"] / 2, (wb, s * y_ski, 0.08)))
        mw.append(("snow_chains", v["w6.chain_mass_kg"], (0.0, s * tr / 2, r)))
    Mw = sum(m for _, m, _ in mw)
    put("dsn.winter_mass_kg", round(Mw, 1), "kg", "winter")
    rd = riders["adult"]
    x_r, y_r, z_r = rider_cg(rd)
    mtw = Mw + rd["mass"]
    cxw = (sum(m * p_[0] for _, m, p_ in mw) + rd["mass"] * x_r) / mtw
    cyw = (sum(m * p_[1] for _, m, p_ in mw) + rd["mass"] * y_r) / mtw
    czw = (sum(m * p_[2] for _, m, p_ in mw) + rd["mass"] * z_r) / mtw
    put("dsn.winter_cg_height_m", round(czw, 3), "m", "winter")
    put("dsn.winter_rear_share", round(1 - cxw / wb, 3), None, "winter")
    # on snow the skis carry the front: the front of the support is their stance
    put("dsn.winter_tip_ratio", round(half_track(cxw, cyw, 2 * y_ski, tr) / czw, 2), None, "stability")
    put("dsn.winter_pitch_ratio", round(min(cxw, wb - cxw) / czw, 2), None, "stability")
    put("dsn.winter_ski_pressure_kpa", round(mtw * G * cxw / wb / (2 * mm("ski.width_mm") * mm("ski.contact_length_mm")) / 1000, 2),
        "kPa", "winter")
    put("dsn.belly_height_mm", round(zp * 1000), "mm", "winter")

    # ---- climbing the slope on long grass with the adult (R-16) -------------------------------
    th = math.atan(v["site.grade_max_pct"] / 100)
    need = m_adult * G * (math.sin(th) + v["ground.crr_max"] * math.cos(th))
    n_rear = m_adult * G * (math.cos(th) * rear_adult + math.sin(th) * h_adult / wb)
    grip = v["ground.mu_grass"] * n_rear
    t_eng = v["eng50.torque_nm"]
    thrust = t_eng * ratio * v["drive.efficiency"] / r
    put("dsn.climb_force_n", round(need), "N", "climb")
    put("dsn.climb_grip_n", round(grip), "N", "climb")
    put("dsn.climb_thrust_n", round(thrust), "N", "climb")
    # the steepest grass slope the rear tyres' grip climbs with the adult
    def climb_margin(th_):
        need_ = math.sin(th_) + v["ground.crr_max"] * math.cos(th_)
        grip_ = v["ground.mu_grass"] * (math.cos(th_) * rear_adult + math.sin(th_) * h_adult / wb)
        return grip_ - need_
    th_max = next(i / 100000 for i in range(0, 80000) if climb_margin(i / 100000) < 0)
    put("dsn.climb_grade_max_pct", round(math.tan(th_max) * 100, 1), '"%"', "climb")

    # ---- strength -----------------------------------------------------------------------------
    k = v["dsn.load_factor"]
    # Axle: a bump on each rear wheel bends it at the outer bearing (wheel load x overhang);
    # the final chain pulls on its sprocket next to the middle bearing at full engine torque.
    # The two act in roughly perpendicular planes and are combined as a vector.
    w_rear = m_adult * G * rear_adult / 2 * k
    arm = tr / 2 - yb
    m_bump = w_rear * arm
    f_chain = t_eng * ratio * v["drive.efficiency"] / (pd_ax / 2)
    m_chain = f_chain * abs(y2 - ybm)
    m_axle = math.hypot(m_bump, m_chain)
    z_axle = math.pi * da ** 3 / 32
    tau_axle = t_eng * ratio * v["drive.efficiency"] * 16 / (math.pi * da ** 3) / 1e6
    sigma_axle = math.hypot(m_axle / z_axle / 1e6, math.sqrt(3) * tau_axle)
    put("dsn.axle_chain_pull_n", round(f_chain), "N", "axle")
    put("dsn.axle_stress_mpa", round(sigma_axle), "MPa", "axle")
    put("dsn.axle_safety", round(v["dsn.s45c_yield_mpa"] / sigma_axle, 2), None, "axle")
    # Frame: the spine as a beam between the rear axle and the front beam carrying every sprung
    # mass and the rider at their x, times the load factor; half on each rail
    unsprung = {"rear_wheels", "rear_hubs", "axle_shaft", "axle_bearings", "front_wheels", "spindles", "brake"}
    loads = [(p_[0], m * G * k) for pt, m, p_ in masses if pt not in unsprung]
    loads.append((x_adult, v["rider.mass_max_kg"] * G * k))
    loads = [(min(max(x, 0.0), wb), f) for x, f in loads]
    r_front = sum(f * x for x, f in loads) / wb
    m_max = 0.0
    for i in range(201):
        xs = wb * i / 200
        mom = r_front * (wb - xs) - sum(f * (x - xs) for x, f in loads if x > xs)
        m_max = max(m_max, abs(mom))
    d_in = rail_od - 2 * rail_t
    z_rail = math.pi * (rail_od ** 4 - d_in ** 4) / (32 * rail_od)
    sigma_rail = m_max / 2 / z_rail / 1e6
    put("dsn.frame_moment_nm", round(m_max), "N m", "frame")
    put("dsn.rail_stress_mpa", round(sigma_rail), "MPa", "frame")
    put("dsn.rail_safety", round(v["dsn.stkm11a_tensile_mpa"] / sigma_rail, 2), None, "frame")
    put("dsn.bearing_load_n", round(w_rear / k), "N", "axle")

    # ---- brake --------------------------------------------------------------------------------
    vt = v["kart.speed_max_kmh"] / 3.6
    a_need = vt * vt / (2 * v["kart.stop_distance_max_m"])
    put("dsn.brake_decel_needed", round(a_need, 2), "m/s2", "brake")
    put("dsn.brake_torque_needed_nm", round(m_adult * a_need * r), "N m", "brake")
    # braking at a_need moves load forward; the rear tyres pass at most mu_paved of what they carry
    n_r = max(m_adult * G * (rear_adult - a_need / G * h_adult / wb), 0.0)
    f_rear = min(v["ground.mu_paved"] * n_r, m_adult * a_need)
    f_front = m_adult * a_need - f_rear
    put("dsn.brake_rear_alone_decel",
        round(v["ground.mu_paved"] * G * rear_adult / (1 + v["ground.mu_paved"] * h_adult / wb), 2), "m/s2", "brake")
    r_eff = dd / 2 - 0.012
    put("dsn.brake_clamp_needed_n", round(f_rear * r / (2 * v["dsn.pad_mu"] * r_eff)), "N", "brake")
    r_eff_f = mm("lay.front_disc_dia_mm") / 2 - 0.012
    put("dsn.brake_front_clamp_needed_n", round(f_front / 2 * r / (2 * v["dsn.pad_mu"] * r_eff_f)), "N", "brake")
    # Downhill on the grass slope: with the rear brake alone the load moves forward off the
    # rear; with the front brakes too every wheel brakes
    n_rear_dn = m_adult * G * (math.cos(th) * rear_adult - math.sin(th) * h_adult / wb)
    a_rear = v["ground.mu_grass"] * n_rear_dn / m_adult - G * math.sin(th)
    put("dsn.brake_downhill_decel_rear", round(a_rear, 2), "m/s2", "brake")
    a_dn = v["ground.mu_grass"] * G * math.cos(th) - G * math.sin(th)
    put("dsn.brake_downhill_decel", round(a_dn, 2), "m/s2", "brake")
    put("dsn.brake_downhill_stop_m", round(vt * vt / (2 * a_dn), 1) if a_dn > 0 else 999, "m", "brake")

    # ---- the Delica ---------------------------------------------------------------------------
    put("dsn.delica_width_margin_mm", round((mm("delica.opening_width_max_mm") - width_t) * 1000), "mm", "transport")
    height = max(zbar + 0.16 + 0.05, zt, zs)
    put("dsn.height_m", round(height, 3), "m", "layout")
    put("dsn.delica_height_margin_mm", round((mm("delica.cargo_height_mm") - height) * 1000), "mm", "transport")
    length = max(xf, wb + r) - min(xb, -r)                    # the tyres may reach past the ends
    put("dsn.length_m", round(length, 3), "m", "layout")
    put("dsn.delica_length_margin_mm", round((mm("delica.cargo_length_mm") - length) * 1000), "mm", "transport")
    length_w = max(length, wb + mm("ski.contact_length_mm") * 0.8 - xb)

    # ---- parts list ---------------------------------------------------------------------------
    bom = tdr.load_yaml((ROOT / "docs" / "data" / "bom.yaml").read_text(encoding="utf-8"))
    totals = {"parts": 0.0, "tools": 0.0}
    for line in bom["lines"]:
        if line["price"] not in v:
            raise SystemExit(f"bom.yaml: price key {line['price']} is not in the record")
        totals[line.get("group", "parts")] += v[line["price"]] * line["qty"]
    put("dsn.bom_parts_jpy", round(totals["parts"]), "JPY", "cost")
    put("dsn.bom_tools_jpy", round(totals["tools"]), "JPY", "cost")

    dims = {"length": length, "width": width, "width_transport": width_t, "height": height, "wheelbase": wb,
            "track_front": tf, "track_rear": tr, "track_rear_narrow": tr, "clearance": zr, "low_point": low,
            "axle_height": r, "x_front": xf, "x_back": xb}
    design = {
        "schema": 1,
        "axes": "x forward, y left, z up, metres; origin on the ground under the rear axle centre",
        "configs": CONFIGS,
        "lift": {"winter": round(lift, 4)},
        "future": ["water"],
        "dims": {k_: round(x, 4) for k_, x in dims.items()},
        "dims_winter": {"length": round(length_w, 4), "height": round(height, 4),
                        "x_front": round(max(xf, wb + r, wb + mm("ski.contact_length_mm") * 0.8), 4),
                        "x_back": round(min(xb, -r), 4), "belly": round(zp, 4), "lift": 0.0},
        "riders": riders,
        "members": members,
        "items": items,
        "masses": [{"part": pt, "kg": round(m, 2), "pos": rnd(p_)} for pt, m, p_ in masses],
        "cg": {"x": round(cx, 4), "z": round(cz, 4), "mass": round(M, 2)},
        "delica": {"length": mm("delica.cargo_length_mm"), "width_max": mm("delica.cargo_width_max_mm"),
                   "width_min": mm("delica.cargo_width_min_mm"), "height": mm("delica.cargo_height_mm"),
                   "opening_min": mm("delica.opening_width_min_mm"), "opening_max": mm("delica.opening_width_max_mm"),
                   "lip": mm("delica.lip_height_mm")},
    }
    return out, design


def as_yaml(out):
    lines = [BEGIN]
    for key, val, unit, sec in out:
        lines += [f"  - key: {key}", f"    v: {val}"]
        if unit:
            lines.append(f"    unit: {unit}")
        lines += ["    status: calculated", "    basis:", f"      - docs/03-design.md#{sec}"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    out, design = build(values())
    text = json.dumps(design, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("ok" if ok else "docs/data/design.json is stale; run python calc/design.py --write")
        sys.exit(0 if ok else 1)
    for key, val, unit, _ in out:
        print(f"{key:32s} {val} {unit or ''}")
    if "--write" in sys.argv:
        p = ROOT / "record" / "values.yaml"
        t = p.read_text(encoding="utf-8")
        block = as_yaml(out)
        if BEGIN in t:
            head, rest = t.split(BEGIN + "\n", 1)
            t = head + block + rest.split(END + "\n", 1)[1]
        else:
            t = t.rstrip("\n") + "\n" + block
        p.write_text(t, encoding="utf-8", newline="\n")
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print("wrote record/values.yaml and docs/data/design.json")


if __name__ == "__main__":
    main()
